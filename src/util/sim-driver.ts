/**
 * Generates the driver script for a player simulation (docs/player-simulation.md). The driver runs from the module's
 * OnModuleLoad in a throwaway build: it spawns a stand-in creature, sets it as MCP_TEST_ACTOR, then runs each step in
 * order. A step runs a generated script (q_act, q_chk, q_roll, a_hen_join, ...) on an NPC with script parameters, as the
 * dialog engine would, and checks what it can see afterwards: a condition's result, a quest stage, gold, an item count.
 * Each step logs `[SIM_OK] label` or `[SIM_FAIL] label: why`; the end logs `[SIM_DONE] ok=N fail=M`.
 */

export interface SimStep {
  label?: string;
  /** Tag of the object the script runs on (OBJECT_SELF); the NPC whose dialog line it is. */
  npc: string;
  script: string;
  params?: Record<string, string>;
  /** A condition script: its result is read back. Default: an action script. */
  kind?: "action" | "condition";
  /** For a condition: the result it must give (default true). */
  expect?: boolean;
  /** Quest stages the stand-in must be at afterwards. */
  expectStage?: Array<{ quest: string; stage: number }>;
  /** Gold the stand-in must have at least. */
  expectGold?: number;
  /** Items (by tag) the stand-in must carry, at least this many. */
  expectItem?: Array<{ tag: string; count?: number }>;
}

export interface SimSpec {
  /** Blueprint of the stand-in (default nw_bartender; use a creature with skill ranks for check tests). */
  actor?: string;
  steps: SimStep[];
}

const IDENT = /^[A-Za-z0-9_]{1,32}$/;

export function nwString(s: string): string {
  return `"${s.replace(/\\/g, "\\\\").replace(/"/g, '\\"').replace(/\r?\n/g, " ")}"`;
}

export function validateSimSpec(spec: SimSpec): string[] {
  const errors: string[] = [];
  if (!Array.isArray(spec.steps) || spec.steps.length === 0) errors.push("steps must be a non-empty array");
  if (spec.actor !== undefined && !IDENT.test(spec.actor) || (spec.actor ?? "").length > 16) errors.push("actor must be a blueprint resref of at most 16 letters, digits or underscores");
  (spec.steps ?? []).forEach((st, i) => {
    const where = `step ${i + 1}`;
    if (!st.npc || st.npc.length > 32 || /["\\]/.test(st.npc)) errors.push(`${where}: npc must be a tag`);
    if (!IDENT.test(st.script ?? "") || st.script.length > 16) errors.push(`${where}: script must be a script resref of at most 16 characters`);
    for (const k of Object.keys(st.params ?? {})) if (!IDENT.test(k)) errors.push(`${where}: parameter name "${k}" is not an identifier`);
  });
  return errors;
}

export function generateSimDriver(spec: SimSpec, originalOnLoad?: string): string {
  const actor = spec.actor ?? "nw_bartender";
  const out: string[] = [];
  out.push(`// a_sim_run: player simulation driver, generated by nwn-mcp (run_live_verification simulate). Throwaway build only.`);
  out.push(`#include "inc_sim"`, "");
  out.push(`void SimOk(string sLabel)
{
    SetLocalInt(GetModule(), "SIM_OKN", GetLocalInt(GetModule(), "SIM_OKN") + 1);
    WriteTimestampedLogEntry("[SIM_OK] " + sLabel);
}

void SimFail(string sLabel, string sWhy)
{
    SetLocalInt(GetModule(), "SIM_FAILN", GetLocalInt(GetModule(), "SIM_FAILN") + 1);
    WriteTimestampedLogEntry("[SIM_FAIL] " + sLabel + ": " + sWhy);
}

int SimItemCount(object oActor, string sTag)
{
    int n = 0;
    object oItem = GetFirstItemInInventory(oActor);
    while (GetIsObjectValid(oItem))
    {
        if (GetTag(oItem) == sTag) n += GetItemStackSize(oItem);
        oItem = GetNextItemInInventory(oActor);
    }
    return n;
}
`);
  spec.steps.forEach((st, i) => {
    const n = i + 1;
    const label = st.label ?? `${st.script} on ${st.npc}`;
    const cond = st.kind === "condition";
    out.push(`void SimStep${n}()
{
    string sLabel = ${nwString(`step ${n}: ${label}`)};
    object oActor = SimActor();
    object oNpc = GetObjectByTag(${nwString(st.npc)});
    if (!GetIsObjectValid(oNpc)) { SimFail(sLabel, "npc not found"); return; }
    int bBad = FALSE;
    DeleteLocalInt(GetModule(), "SIM_COND");`);
    for (const [k, v] of Object.entries(st.params ?? {})) out.push(`    SetScriptParam(${nwString(k)}, ${nwString(String(v))});`);
    out.push(`    ExecuteScript(${nwString(st.script)}, oNpc);`);
    if (cond) {
      const want = st.expect === false ? 0 : 1;
      out.push(`    int nCond = GetLocalInt(GetModule(), "SIM_COND") - 1;
    if (nCond < 0) { SimFail(sLabel, "the condition script did not report a result"); bBad = TRUE; }
    else if (nCond != ${want}) { SimFail(sLabel, "condition gave " + IntToString(nCond) + ", expected ${want}"); bBad = TRUE; }`);
    }
    for (const e of st.expectStage ?? []) {
      out.push(`    if (GetLocalInt(oActor, "NW_JOURNAL_ENTRY" + ${nwString(e.quest)}) != ${Math.trunc(e.stage)}) { SimFail(sLabel, "quest ${e.quest} is at stage " + IntToString(GetLocalInt(oActor, "NW_JOURNAL_ENTRY" + ${nwString(e.quest)})) + ", expected ${Math.trunc(e.stage)}"); bBad = TRUE; }`);
    }
    if (st.expectGold !== undefined) {
      out.push(`    if (GetGold(oActor) < ${Math.trunc(st.expectGold)}) { SimFail(sLabel, "gold is " + IntToString(GetGold(oActor)) + ", expected at least ${Math.trunc(st.expectGold)}"); bBad = TRUE; }`);
    }
    for (const it of st.expectItem ?? []) {
      const c = Math.trunc(it.count ?? 1);
      out.push(`    if (SimItemCount(oActor, ${nwString(it.tag)}) < ${c}) { SimFail(sLabel, "carries " + IntToString(SimItemCount(oActor, ${nwString(it.tag)})) + " of ${it.tag.replace(/["\\]/g, "")}, expected at least ${c}"); bBad = TRUE; }`);
    }
    out.push(`    if (!bBad) SimOk(sLabel);
}
`);
  });
  out.push(`void SimDone()
{
    WriteTimestampedLogEntry("[SIM_DONE] ok=" + IntToString(GetLocalInt(GetModule(), "SIM_OKN")) + " fail=" + IntToString(GetLocalInt(GetModule(), "SIM_FAILN")));
}

void SimRun()
{
    object oActor = CreateObject(OBJECT_TYPE_CREATURE, ${nwString(actor)}, GetStartingLocation());
    if (!GetIsObjectValid(oActor)) { SimFail("setup", "stand-in blueprint not found"); SimDone(); return; }
    SetPlotFlag(oActor, TRUE);
    SetLocalObject(GetModule(), "MCP_TEST_ACTOR", oActor);`);
  for (let i = 1; i <= spec.steps.length; i++) out.push(`    DelayCommand(${i}.0, SimStep${i}());`);
  out.push(`    DelayCommand(${spec.steps.length + 1}.0, SimDone());
}

void main()
{`);
  if (originalOnLoad) out.push(`    ExecuteScript(${nwString(originalOnLoad)}, OBJECT_SELF);`);
  out.push(`    DelayCommand(3.0, SimRun());
}
`);
  return out.join("\n");
}
