/**
 * Tests for the generic runtime-assertion include generator.
 *
 * Same constraint as spec-check-script.test.ts: the generated source can't be
 * compiled here (needs the NWN data tree + nim toolchain — create_spec_assertions
 * does that with a probe script at runtime). These assert on the shape that
 * makes the include correct: the verify-mode gate, the exact [SPEC_OK]/
 * [SPEC_FAIL] log line format (must match src/util/verify-server/result.ts's
 * parser regexes), and the three assertion primitives' signatures.
 */

import { describe, expect, it } from "vitest";
import { generateSpecAssertInclude } from "./spec-assert-script.js";
import { parseLiveLogs } from "./verify-server/result.js";

describe("generateSpecAssertInclude — gating", () => {
  it("gates all three assertion functions behind MCP_VERIFY_MODE", () => {
    const source = generateSpecAssertInclude();
    const functions = source.split(/^void SPEC_Assert/m).slice(1);
    expect(functions.length).toBe(3);
    for (const fn of functions) {
      expect(fn).toContain('if (!GetLocalInt(GetModule(), "MCP_VERIFY_MODE")) return;');
    }
  });

  it("uses the default include name in the usage comment, or a custom one", () => {
    expect(generateSpecAssertInclude()).toContain('#include "inc_spec_assert"');
    expect(generateSpecAssertInclude({ includeName: "inc_spa" })).toContain('#include "inc_spa"');
  });

  it("marks the file as generated, not hand-editable", () => {
    const source = generateSpecAssertInclude();
    expect(source).toMatch(/GENERATED by nwn-mcp create_spec_assertions/);
  });
});

describe("generateSpecAssertInclude — signatures", () => {
  const source = generateSpecAssertInclude();

  it("declares SPEC_AssertInt(string, string, int, int)", () => {
    expect(source).toContain("void SPEC_AssertInt(string sTag, string sField, int nExpected, int nActual)");
  });

  it("declares SPEC_AssertString(string, string, string, string)", () => {
    expect(source).toContain("void SPEC_AssertString(string sTag, string sField, string sExpected, string sActual)");
  });

  it("declares SPEC_AssertBool with a defaulted description param", () => {
    expect(source).toContain(
      'void SPEC_AssertBool(string sTag, string sField, int bCondition, string sActualDescription = "")',
    );
  });
});

describe("generateSpecAssertInclude — log format matches the existing live-log parser", () => {
  it("SPEC_AssertInt's OK/FAIL lines are recognized by parseLiveLogs", () => {
    const okLine = "[SPEC_OK] tag=my_tag field=my_field";
    const failLine = "[SPEC_FAIL] tag=my_tag field=my_field expected=5 actual=3";
    const parsed = parseLiveLogs(`${okLine}\n${failLine}`, "");
    expect(parsed.specResults.ok).toEqual(["my_tag"]);
    expect(parsed.specResults.fail).toEqual([{ tag: "my_tag", field: "my_field", expected: "5", actual: "3" }]);
  });

  it("source emits exactly this OK/FAIL shape for SPEC_AssertInt", () => {
    const source = generateSpecAssertInclude();
    const fn = source.slice(source.indexOf("void SPEC_AssertInt"), source.indexOf("void SPEC_AssertString"));
    expect(fn).toContain('"[SPEC_OK] tag=" + sTag + " field=" + sField');
    expect(fn).toContain('"[SPEC_FAIL] tag=" + sTag + " field=" + sField +');
    expect(fn).toContain('" expected=" + IntToString(nExpected) + " actual=" + IntToString(nActual)');
  });

  it("source emits exactly this OK/FAIL shape for SPEC_AssertString", () => {
    const source = generateSpecAssertInclude();
    const fn = source.slice(source.indexOf("void SPEC_AssertString"), source.indexOf("void SPEC_AssertBool"));
    expect(fn).toContain('"[SPEC_OK] tag=" + sTag + " field=" + sField');
    expect(fn).toContain('" expected=" + sExpected + " actual=" + sActual');
  });

  it("source emits exactly this OK/FAIL shape for SPEC_AssertBool, always expecting TRUE", () => {
    const source = generateSpecAssertInclude();
    const fn = source.slice(source.indexOf("void SPEC_AssertBool"));
    expect(fn).toContain('"[SPEC_OK] tag=" + sTag + " field=" + sField');
    expect(fn).toContain('" expected=TRUE actual=" + sActual');
  });

  it("SPEC_AssertBool's described-failure line is recognized by parseLiveLogs too", () => {
    const failLine = "[SPEC_FAIL] tag=my_enc field=hostile expected=TRUE actual=not_enemies";
    const parsed = parseLiveLogs(failLine, "");
    expect(parsed.specResults.fail).toEqual([
      { tag: "my_enc", field: "hostile", expected: "TRUE", actual: "not_enemies" },
    ]);
  });
});

describe("generateSpecAssertInclude — each assertion logs immediately and independently", () => {
  it("has no shared pass-tracking state across the three functions (no bundling)", () => {
    // Regression guard: unlike SPEC_VerifyCreature's one-line-after-all-fields
    // bundling, these are meant to be bare, independent primitives — a caller
    // that wants bundling tracks its own flag. No shared module/global state
    // should exist for that purpose here.
    const source = generateSpecAssertInclude();
    expect(source).not.toMatch(/int\s+\w*bPass\w*\s*=/);
  });
});
