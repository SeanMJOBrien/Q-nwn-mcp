/**
 * inc_sim: the test-actor hook (docs/player-simulation.md). The headless verify server has no player. A driver script
 * sets the module local object MCP_TEST_ACTOR to a stand-in creature; the generated quest and companion scripts then treat
 * that creature as the player (`SimIsPlayer`, `SimSpeaker`, `SimFirstPC`/`SimNextPC`). With the local unset, behaviour is
 * exactly the engine's own, so real players are unaffected.
 */

export const SIM_INCLUDE = "inc_sim";
export const TEST_ACTOR_VAR = "MCP_TEST_ACTOR";

export function generateSimInclude(): string {
  return `// inc_sim: test-actor hook, generated by nwn-mcp. See docs/player-simulation.md in nwn-mcp.
// Set the module local object ${TEST_ACTOR_VAR} to a creature to make generated scripts treat it as the player.

object SimActor()
{
    return GetLocalObject(GetModule(), "${TEST_ACTOR_VAR}");
}

int SimIsPlayer(object oObject)
{
    if (!GetIsObjectValid(oObject)) return FALSE;
    if (GetIsPC(oObject)) return TRUE;
    return oObject == SimActor();
}

// The player talking to this NPC: the test actor when set, else the real speaker.
object SimSpeaker()
{
    object oActor = SimActor();
    if (GetIsObjectValid(oActor)) return oActor;
    return GetPCSpeaker();
}

// Player-only party walk. The test actor is a party of one.
object SimFirstPC(object oPC)
{
    if (GetIsObjectValid(oPC) && oPC == SimActor()) return oPC;
    return GetFirstFactionMember(oPC, TRUE);
}

object SimNextPC(object oPC)
{
    if (GetIsObjectValid(oPC) && oPC == SimActor()) return OBJECT_INVALID;
    return GetNextFactionMember(oPC, TRUE);
}
`;
}
