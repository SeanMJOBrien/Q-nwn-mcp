import { generateSimInclude, SIM_INCLUDE, withSimResult } from "./sim-script.js";
/**
 * Generator for the parameter-driven quest runtime written by `create_quest_system`.
 *
 * Ported from The Frozen North's `inc_quest.nss` + `dlg_q_*` scripts and the TFN content studio's courier/rescue/escort
 * runtime, with these changes:
 *   - vanilla: quest state is the engine's own `NW_JOURNAL_ENTRY<tag>` local (no SQLite, no NWNX);
 *   - whole party: an advance moves every party member's journal (AddJournalQuestEntry bAllPartyMembers) and pays every
 *     player 100 % (the project's co-op rule); eligibility is TFN's (exactly one stage behind unless a jump is allowed,
 *     prerequisites met, not already there), so a second party member can't advance or be paid again;
 *   - kills and pickups by companions, summons and familiars credit their master; a kill nobody in a party made credits
 *     the nearest player within 30 m;
 *   - fixes: AoE advances use their own stage (TFN always advanced quest1), slots go to 20 (TFN stopped at 19), skill
 *     checks are an action that rolls once (TFN rolled Bluff, shifted alignment and advanced inside a condition), reward
 *     items are checked, stage numbers aren't limited to two digits;
 *   - every advance logs `[QUEST] advance tag= stage= via= pc= object=` for run_live_verification.
 *
 * Variable contract on a quest object (NPC, creature, item, area, trigger, placeable), slot K = 1..20:
 *   questK = "<stage>_<tag>", questK_prereq1..9 = "<stage>_<tag>", questK_jumpstage = 1,
 *   questK_reward_xp_tier (1-4) + questK_reward_xp_level, questK_reward_xp (flat), questK_reward_gold,
 *   questK_reward_item (resref),
 *   questK_pc_script, questK_self_script, questK_bounty_end = 1,
 *   questK_escort_area / _point / _x / _y / _radius / _arrive / _leave (escort destination).
 * Event objects also carry quest_event = K (TFN's quest_kill = K is accepted on creatures).
 */

