/**
 * Generator for the random-treasure include (TODO #52): The Frozen North's loot selection, ported to a self-contained module include.
 *
 * What is ported: the way that world picks a random item. (1) a kind of treasure by fixed weights (potions most, then jewels, scrolls,
 * melee, ranged, apparel, ...), (2) a value tier by weights that depend on the area's challenge rating: every tier has a base weight
 * and a sigmoid midpoint, so tier 1 is always there, tier 2 grows with the CR, and tiers 3, 4 and 5 start to appear around CR 7, 10 and
 * 13 (`weight = base * CR * max(0, (68 + atan((CR - midpoint) * 0.6)) / 158)`, raised to 1 + a quality modifier), (3) a random item
 * of that kind and tier from the pool. Containers roll one, two or three items by fixed chances times a quantity multiplier.
 *
 * What differs: the source world sorts its item blueprints into staging chests at server start; here the pool is baked into the
 * include as JSON (kind -> tier -> resrefs), built by `create_treasure_system` from items that exist in the module (hand-made or
 * imported with `import_treasure_item`) and base-game items. No NWNX, no database, no staging area.
 */

export const TREASURE_INCLUDE = "inc_treasure";
export const TREASURE_OPEN_SCRIPT = "a_trs_open";
export const TREASURE_DEATH_SCRIPT = "a_trs_death";

/** Loot kinds, in the source world's order. The pool is keyed by these numbers. */
export const TREASURE_KINDS = [
  "misccons", // 0: consumables other than potions and scrolls (wands, rods)
  "misc", // 1: gems, junk, art
  "scroll", // 2
  "potion", // 3
  "melee", // 4
  "range", // 5: bows, crossbows, slings, ammunition, thrown weapons
  "armor", // 6: armour, shields, helmets
  "apparel", // 7: cloaks, boots, gloves, belts
  "jewel", // 8: rings and amulets
] as const;

export type TreasureKind = (typeof TREASURE_KINDS)[number];

/** Kind weights of the source world (potions are the most common find). Index = kind number. */
export const KIND_WEIGHTS = [2, 3, 6, 12, 5, 4, 2, 4, 7] as const;

/** Pool of resrefs: kind number -> tier (1-5) -> resrefs. */
export type TreasurePool = Record<string, Record<string, string[]>>;

/** Map a catalog item group (util/treasure-catalog.ts treasureGroup) to a loot kind number. */
export function kindOfGroup(group: string): number {
  switch (group) {
    case "weapon":
      return 4;
    case "ranged":
    case "ammo":
    case "thrown":
      return 5;
    case "armor":
    case "shield":
    case "helmet":
      return 6;
    case "cloak":
    case "boots":
    case "gloves":
    case "belt":
      return 7;
    case "ring":
    case "amulet":
      return 8;
    case "potion":
      return 3;
    case "scroll":
      return 2;
    case "wand":
      return 0;
    default:
      return 1;
  }
}

export function emptyPool(): TreasurePool {
  return {};
}

export function addToPool(pool: TreasurePool, kind: number, tier: number, resref: string): void {
  const k = String(kind);
  const t = String(Math.min(5, Math.max(1, tier)));
  pool[k] ??= {};
  pool[k][t] ??= [];
  if (!pool[k][t].includes(resref)) pool[k][t].push(resref);
}

export function poolSize(pool: TreasurePool): number {
  let n = 0;
  for (const tiers of Object.values(pool)) for (const list of Object.values(tiers)) n += list.length;
  return n;
}

/** NWScript string literal for JSON text. */
function nwString(s: string): string {
  return `"${s.replace(/\\/g, "\\\\").replace(/"/g, '\\"')}"`;
}

export function generateTreasureInclude(pool: TreasurePool): string {
  // The compiler caps a string literal around 32 KB; split the pool across several constants.
  const json = JSON.stringify(pool);
  const parts: string[] = [];
  for (let i = 0; i < json.length; i += 8000) parts.push(json.slice(i, i + 8000));
  const poolDecl = parts.map((p, i) => `const string TR_POOL_${i} = ${nwString(p)};`).join("\n");
  const poolExpr = parts.map((_, i) => `TR_POOL_${i}`).join(" + ");
  return `// ${TREASURE_INCLUDE}: random treasure by area challenge rating, weights ported from a hand-built world's loot system.
// Generated by create_treasure_system. API: TR_RollItem, TR_AddItem, TR_Fill, TR_FillOnce.

// --- Weights (the source world's values)
const int TR_BASE_T1 = 2000;
const int TR_BASE_T2 = 200;
const int TR_BASE_T3 = 100;
const int TR_BASE_T4 = 50;
const int TR_BASE_T5 = 20;
const int TR_MID_T1 = 1;
const int TR_MID_T2 = 1;
const int TR_MID_T3 = 7;
const int TR_MID_T4 = 10;
const int TR_MID_T5 = 13;

// Chance (percent) that a container holds at least one, two or three items, times its quantity multiplier.
const int TR_CHANCE_ONE = 35;
const int TR_CHANCE_TWO = 15;
const int TR_CHANCE_THREE = 5;

// Quality modifier: below 0 squashes the tier weights together (better items more likely), above 0 widens the gap.
const float TR_QUALITY_LOW = 0.4;
const float TR_QUALITY_MEDIUM = 0.0;
const float TR_QUALITY_HIGH = -0.2;
const float TR_QUALITY_BOSS = -0.7;
// Consumables lean toward higher tiers than gear does.
const float TR_POTION_QUALITY = -0.3;
const float TR_SCROLL_QUALITY = -0.2;
const float TR_MISCCONS_QUALITY = -0.2;

// Kind numbers (the pool's keys) and their weights.
const int TR_KIND_MISCCONS = 0;
const int TR_KIND_MISC = 1;
const int TR_KIND_SCROLL = 2;
const int TR_KIND_POTION = 3;
const int TR_KIND_MELEE = 4;
const int TR_KIND_RANGE = 5;
const int TR_KIND_ARMOR = 6;
const int TR_KIND_APPAREL = 7;
const int TR_KIND_JEWEL = 8;
// Allowed-kinds bitmask: 1 << kind. TR_ANY allows every kind.
const int TR_ANY = 511;
const int TR_GEAR = 496;       // melee, range, armor, apparel
const int TR_CONSUMABLE = 13;  // misccons, scroll, potion

${poolDecl}

int TR_KindWeight(int nKind)
{
    switch (nKind)
    {
        case 0: return ${KIND_WEIGHTS[0]};
        case 1: return ${KIND_WEIGHTS[1]};
        case 2: return ${KIND_WEIGHTS[2]};
        case 3: return ${KIND_WEIGHTS[3]};
        case 4: return ${KIND_WEIGHTS[4]};
        case 5: return ${KIND_WEIGHTS[5]};
        case 6: return ${KIND_WEIGHTS[6]};
        case 7: return ${KIND_WEIGHTS[7]};
        case 8: return ${KIND_WEIGHTS[8]};
    }
    return 0;
}

// The pool, parsed once and kept on the module object.
json TR_Pool()
{
    object oMod = GetModule();
    json jPool = GetLocalJson(oMod, "TR_POOL");
    if (JsonGetType(jPool) != JSON_TYPE_OBJECT)
    {
        jPool = JsonParse(${poolExpr});
        SetLocalJson(oMod, "TR_POOL", jPool);
    }
    return jPool;
}

// Resrefs of one kind and tier (empty array when the pool has none).
json TR_List(int nKind, int nTier)
{
    json jKind = JsonObjectGet(TR_Pool(), IntToString(nKind));
    if (JsonGetType(jKind) != JSON_TYPE_OBJECT) return JsonArray();
    json jList = JsonObjectGet(jKind, IntToString(nTier));
    if (JsonGetType(jList) != JSON_TYPE_ARRAY) return JsonArray();
    return jList;
}

// Weight of one tier for an area challenge rating: base * CR (tier 1: base only) shaped by a sigmoid around the tier's midpoint.
int TR_TierWeight(int nCR, int nTier, int nKind, float fQuality)
{
    int nBase = 0;
    int nMid = 0;
    if (nTier == 1) { nBase = TR_BASE_T1; nMid = TR_MID_T1; }
    else if (nTier == 2) { nBase = nCR * TR_BASE_T2; nMid = TR_MID_T2; }
    else if (nTier == 3) { nBase = nCR * TR_BASE_T3; nMid = TR_MID_T3; }
    else if (nTier == 4) { nBase = nCR * TR_BASE_T4; nMid = TR_MID_T4; }
    else if (nTier == 5) { nBase = nCR * TR_BASE_T5; nMid = TR_MID_T5; }
    else return 0;
    float fShape = (68.0 + atan((nCR - nMid) * 0.6)) / 158.0;
    if (fShape < 0.0) fShape = 0.0;
    float fWeight = nBase * fShape;
    if (fWeight <= 0.0) return 0;
    float fExponent = 1.0 + fQuality;
    if (nKind == TR_KIND_POTION) fExponent += TR_POTION_QUALITY;
    else if (nKind == TR_KIND_SCROLL) fExponent += TR_SCROLL_QUALITY;
    else if (nKind == TR_KIND_MISCCONS) fExponent += TR_MISCCONS_QUALITY;
    return FloatToInt(pow(fWeight, fExponent) * 1000.0);
}

// A kind picked by weight among those allowed by nMask that have anything in the pool; -1 when none.
int TR_PickKind(int nMask)
{
    int nTotal = 0;
    int nKind;
    for (nKind = 0; nKind <= 8; nKind++)
    {
        if (!(nMask & (1 << nKind))) continue;
        int nHas = 0;
        int nTier;
        for (nTier = 1; nTier <= 5; nTier++) nHas += JsonGetLength(TR_List(nKind, nTier));
        if (nHas > 0) nTotal += TR_KindWeight(nKind);
    }
    if (nTotal <= 0) return -1;
    int nRoll = Random(nTotal);
    for (nKind = 0; nKind <= 8; nKind++)
    {
        if (!(nMask & (1 << nKind))) continue;
        int nHas2 = 0;
        int nTier2;
        for (nTier2 = 1; nTier2 <= 5; nTier2++) nHas2 += JsonGetLength(TR_List(nKind, nTier2));
        if (nHas2 <= 0) continue;
        nRoll -= TR_KindWeight(nKind);
        if (nRoll < 0) return nKind;
    }
    return -1;
}

// A tier picked by the challenge-rating weights among those the kind has items for; -1 when the kind is empty.
int TR_PickTier(int nCR, int nKind, float fQuality)
{
    int nTotal = 0;
    int nTier;
    int nW1 = 0; int nW2 = 0; int nW3 = 0; int nW4 = 0; int nW5 = 0;
    if (JsonGetLength(TR_List(nKind, 1)) > 0) nW1 = TR_TierWeight(nCR, 1, nKind, fQuality);
    if (JsonGetLength(TR_List(nKind, 2)) > 0) nW2 = TR_TierWeight(nCR, 2, nKind, fQuality);
    if (JsonGetLength(TR_List(nKind, 3)) > 0) nW3 = TR_TierWeight(nCR, 3, nKind, fQuality);
    if (JsonGetLength(TR_List(nKind, 4)) > 0) nW4 = TR_TierWeight(nCR, 4, nKind, fQuality);
    if (JsonGetLength(TR_List(nKind, 5)) > 0) nW5 = TR_TierWeight(nCR, 5, nKind, fQuality);
    nTotal = nW1 + nW2 + nW3 + nW4 + nW5;
    if (nTotal <= 0)
    {
        // Nothing weighted (a CR too low for the only tiers present): take the lowest tier that has items.
        for (nTier = 1; nTier <= 5; nTier++) if (JsonGetLength(TR_List(nKind, nTier)) > 0) return nTier;
        return -1;
    }
    int nRoll = Random(nTotal);
    nRoll -= nW1; if (nRoll < 0) return 1;
    nRoll -= nW2; if (nRoll < 0) return 2;
    nRoll -= nW3; if (nRoll < 0) return 3;
    nRoll -= nW4; if (nRoll < 0) return 4;
    return 5;
}

// A random item resref for an area challenge rating. nMask limits the kinds (TR_ANY, TR_GEAR, 1 << TR_KIND_JEWEL, ...);
// fQuality shifts the tier weights (TR_QUALITY_*). Returns "" when the pool has nothing allowed.
string TR_RollItem(int nCR, int nMask = 511, float fQuality = 0.0)
{
    int nKind = TR_PickKind(nMask);
    if (nKind < 0) return "";
    int nTier = TR_PickTier(nCR, nKind, fQuality);
    if (nTier < 0) return "";
    json jList = TR_List(nKind, nTier);
    int nLen = JsonGetLength(jList);
    if (nLen <= 0) return "";
    return JsonGetString(JsonArrayGet(jList, Random(nLen)));
}

// Create one random item in oTarget's inventory; returns it (OBJECT_INVALID when none could be made).
object TR_AddItem(object oTarget, int nCR, int nMask = 511, float fQuality = 0.0)
{
    string sResRef = TR_RollItem(nCR, nMask, fQuality);
    if (sResRef == "") return OBJECT_INVALID;
    return CreateItemOnObject(sResRef, oTarget);
}

// Fill oTarget with random items. fQuantity multiplies the one/two/three-item chances (1.0 usual, 1.75 medium, 3.0 rich);
// nGuaranteed items are always made on top of the chance rolls (use it for rewards).
void TR_Fill(object oTarget, int nCR, float fQuantity = 1.0, int nMask = 511, float fQuality = 0.0, int nGuaranteed = 0)
{
    if (!GetIsObjectValid(oTarget)) return;
    int nCount = nGuaranteed;
    if (Random(100) < FloatToInt(TR_CHANCE_ONE * fQuantity)) nCount++;
    if (Random(100) < FloatToInt(TR_CHANCE_TWO * fQuantity)) nCount++;
    if (Random(100) < FloatToInt(TR_CHANCE_THREE * fQuantity)) nCount++;
    int i;
    for (i = 0; i < nCount; i++) TR_AddItem(oTarget, nCR, nMask, fQuality);
}

// Challenge rating for a container: its own TR_CR, else its area's, else the module's, else 1.
int TR_AreaCR(object oSource)
{
    int nCR = GetLocalInt(oSource, "TR_CR");
    if (nCR <= 0) nCR = GetLocalInt(GetArea(oSource), "TR_CR");
    if (nCR <= 0) nCR = GetLocalInt(GetModule(), "TR_CR");
    return nCR > 0 ? nCR : 1;
}

// Fill a container once, the first time it is opened: locals on the container TR_CR (default: area, module), TR_QUANTITY
// (float, default 1.0), TR_QUALITY (float, default 0.0), TR_MASK (kinds, default all), TR_GUARANTEED (default 0).
void TR_FillOnce(object oContainer)
{
    if (GetLocalInt(oContainer, "TR_FILLED")) return;
    SetLocalInt(oContainer, "TR_FILLED", 1);
    float fQuantity = GetLocalFloat(oContainer, "TR_QUANTITY");
    if (fQuantity <= 0.0) fQuantity = 1.0;
    int nMask = GetLocalInt(oContainer, "TR_MASK");
    if (nMask <= 0) nMask = TR_ANY;
    TR_Fill(oContainer, TR_AreaCR(oContainer), fQuantity, nMask, GetLocalFloat(oContainer, "TR_QUALITY"), GetLocalInt(oContainer, "TR_GUARANTEED"));
}

// --- Creature drops and boss rewards

// Tier of the item a boss kill guarantees, by area challenge rating (semi-bosses count as 70 % of it): tier 2 below CR 3, tier 3 from
// CR 3 (15 % at CR 3 rising to 80 % at CR 5), tier 4 from CR 6 (10 % rising to 70 % at CR 9), tier 5 from CR 10 (5 % rising to 80 % at CR 13).
int TR_BossTier(int nCR, int bSemiboss)
{
    if (bSemiboss) nCR = FloatToInt(nCR * 0.7 + 0.5);
    if (nCR < 3) return 2;
    if (nCR == 3) return Random(100) < 15 ? 3 : 2;
    if (nCR == 4) return Random(100) < 50 ? 3 : 2;
    if (nCR == 5) return Random(100) < 80 ? 3 : 2;
    if (nCR == 6) return Random(100) < 10 ? 4 : 3;
    if (nCR == 7) return Random(100) < 25 ? 4 : 3;
    if (nCR == 8) return Random(100) < 50 ? 4 : 3;
    if (nCR == 9) return Random(100) < 70 ? 4 : 3;
    if (nCR == 10) return Random(100) < 5 ? 5 : 4;
    if (nCR == 11) return Random(100) < 15 ? 5 : 4;
    if (nCR == 12) return Random(100) < 40 ? 5 : 4;
    if (nCR == 13) return Random(100) < 80 ? 5 : 4;
    return 5;
}

// One item of exactly this tier (a kind picked by weight among those with items at the tier); falls back to the nearest tier below,
// then above, when the pool has nothing at it. Returns "" when the pool is empty for the mask.
string TR_RollItemOfTier(int nTier, int nMask = 511)
{
    int nTry;
    for (nTry = 0; nTry <= 4; nTry++)
    {
        int nT = nTier - nTry;
        if (nT < 1) nT = nTier + (nTry - nTier + 1);
        if (nT < 1 || nT > 5) continue;
        int nTotal = 0;
        int nKind;
        for (nKind = 0; nKind <= 8; nKind++)
            if ((nMask & (1 << nKind)) && JsonGetLength(TR_List(nKind, nT)) > 0) nTotal += TR_KindWeight(nKind);
        if (nTotal <= 0) continue;
        int nRoll = Random(nTotal);
        for (nKind = 0; nKind <= 8; nKind++)
        {
            if (!(nMask & (1 << nKind)) || JsonGetLength(TR_List(nKind, nT)) <= 0) continue;
            nRoll -= TR_KindWeight(nKind);
            if (nRoll < 0)
            {
                json jList = TR_List(nKind, nT);
                return JsonGetString(JsonArrayGet(jList, Random(JsonGetLength(jList))));
            }
        }
    }
    return "";
}

// Percent chance that a creature of challenge rating nMonsterCR drops treasure in an area of nAreaCR: 30, doubled for every two ratings
// above the area, halved for every two below, never above 100.
int TR_DropChance(int nMonsterCR, int nAreaCR)
{
    float fChance = 30.0 * pow(2.0, (nMonsterCR - nAreaCR) / 2.0);
    return fChance > 100.0 ? 100 : FloatToInt(fChance);
}

// Treasure for a creature that has just died, put in its own inventory (the lootable body). Locals on the creature: TR_BOSS (1 boss,
// 2 semi-boss: one item of the boss tier is guaranteed on top), TR_CR (area rating override), TR_QUANTITY, TR_QUALITY, TR_MASK.
void TR_DropOnDeath(object oCreature)
{
    if (!GetIsObjectValid(oCreature) || GetLocalInt(oCreature, "TR_DROPPED")) return;
    SetLocalInt(oCreature, "TR_DROPPED", 1);
    int nAreaCR = TR_AreaCR(oCreature);
    int nBoss = GetLocalInt(oCreature, "TR_BOSS");
    int nMask = GetLocalInt(oCreature, "TR_MASK");
    if (nMask <= 0) nMask = TR_ANY;
    if (nBoss > 0)
    {
        string sBoss = TR_RollItemOfTier(TR_BossTier(nAreaCR, nBoss == 2), nMask);
        if (sBoss != "") CreateItemOnObject(sBoss, oCreature);
    }
    if (Random(100) >= TR_DropChance(FloatToInt(GetChallengeRating(oCreature)), nAreaCR)) return;
    float fQuantity = GetLocalFloat(oCreature, "TR_QUANTITY");
    if (fQuantity <= 0.0) fQuantity = 1.0;
    // The chance roll above already decided there is loot: the one/two/three-item rolls then decide how much, at least one.
    TR_Fill(oCreature, nAreaCR, fQuantity, nMask, GetLocalFloat(oCreature, "TR_QUALITY"), 1);
}
`;
}

/** Creature OnDeath script: runs the creature's own death script (TR_ORIG_DEATH, default nw_c2_default7), then drops treasure (see TR_DropOnDeath). */
export function generateTreasureDeathScript(): string {
  return `// ${TREASURE_DEATH_SCRIPT}: creature OnDeath. Runs the original death script, then drops random treasure by challenge rating.
#include "${TREASURE_INCLUDE}"

void main()
{
    string sOriginal = GetLocalString(OBJECT_SELF, "TR_ORIG_DEATH");
    if (sOriginal == "") sOriginal = "nw_c2_default7";
    ExecuteScript(sOriginal, OBJECT_SELF);
    TR_DropOnDeath(OBJECT_SELF);
}
`;
}

/** OnOpen script for a container: fills it once with random treasure (see TR_FillOnce for the locals that tune it). */
export function generateTreasureOpenScript(): string {
  return `// ${TREASURE_OPEN_SCRIPT}: container OnOpen. Fills the container once with random treasure for its area's challenge rating.
#include "${TREASURE_INCLUDE}"

void main()
{
    TR_FillOnce(OBJECT_SELF);
}
`;
}
