import { generateSimInclude, SIM_INCLUDE, withSimResult } from "./sim-script.js";
/**
 * Generator for the shared companion (henchman) scripts written by `create_companion_system`.
 *
 * The party cap is computed from the engine every time (living henchmen of every PC in the
 * recruiting PC's party), never kept in a counter. The hand-written scripts this replaces kept a
 * module int that had to be decremented on dismiss and on death; each missed path permanently
 * blocked recruiting (both happened in The Hollow Communion playtests), and the death decrement
 * also fired for a companion that was never recruited.
 *
 * All functions used are EE engine built-ins (AddHenchman, RemoveHenchman, GetMaster,
 * GetAssociateType, SetAssociateListenPatterns, SetMaxHenchmen), so nothing includes a stock
 * BioWare library. Orders go through the stock associate AI's silent shouts
 * (HENCHMAN_CMD_FOLLOW / HENCHMAN_CMD_STANDGROUND), which it hears once listen patterns are set.
 */

export const COMPANION_INCLUDE = "inc_companion";

/** Every script resref the system writes, in write order (include first). */
export const COMPANION_SCRIPTS = [
  COMPANION_INCLUDE,
  "c_hen_free",
  "c_hen_mine",
  "c_hen_full",
  "a_hen_join",
  "a_hen_leave",
  "a_hen_stay",
  "a_hen_follow",
] as const;

export const DEFAULT_MAX_COMPANIONS = 3;

export interface CompanionScriptOptions {
  /** Companions allowed in the whole party at once (all PCs combined). */
  maxCompanions?: number;
}

function include(max: number): string {
  return `// inc_companion: shared companion (henchman) logic, generated by create_companion_system.
// The party cap is counted from the engine each time; there is no counter to keep in step.

#include "inc_sim"

// --- Configuration
const int CMP_MAX_COMPANIONS = ${max};

// TRUE when oCreature is a living henchman whose master is a PC.
int CMP_IsLivingCompanion(object oCreature)
{
    if (!GetIsObjectValid(oCreature) || SimIsPlayer(oCreature) || GetIsDead(oCreature)) return FALSE;
    if (GetAssociateType(oCreature) != ASSOCIATE_TYPE_HENCHMAN) return FALSE;
    return SimIsPlayer(GetMaster(oCreature));
}

// Living companions across oPC's whole party (every PC's henchmen).
int CMP_PartyCompanionCount(object oPC)
{
    int nCount = 0;
    object oMember = GetFirstFactionMember(oPC, FALSE);
    while (GetIsObjectValid(oMember))
    {
        if (CMP_IsLivingCompanion(oMember)) nCount++;
        oMember = GetNextFactionMember(oPC, FALSE);
    }
    return nCount;
}

// TRUE when oPC's party has room for another companion.
int CMP_PartyHasRoom(object oPC)
{
    return CMP_PartyCompanionCount(oPC) < CMP_MAX_COMPANIONS;
}

// Recruit oHenchman to oPC. Returns FALSE (and does nothing) when the party is full.
int CMP_Join(object oHenchman, object oPC)
{
    if (!GetIsObjectValid(oHenchman) || !GetIsObjectValid(oPC)) return FALSE;
    if (GetMaster(oHenchman) == oPC) return TRUE;
    if (!CMP_PartyHasRoom(oPC)) return FALSE;

    // AddHenchman is a silent no-op when the per-PC cap is too low.
    if (GetMaxHenchmen() < CMP_MAX_COMPANIONS + 1) SetMaxHenchmen(CMP_MAX_COMPANIONS + 1);
    // Without listen patterns the companion ignores every follow/stand-ground order.
    SetAssociateListenPatterns(oHenchman);
    AddHenchman(oPC, oHenchman);
    // Start every (re)join in follow mode: a stand-ground order given before a dismissal survives it.
    AssignCommand(oPC, SpeakString("HENCHMAN_CMD_FOLLOW", TALKVOLUME_SILENT_SHOUT));
    return GetMaster(oHenchman) == oPC;
}

// Dismiss oHenchman from whoever leads it; it goes back to the Commoner faction and stays put.
void CMP_Leave(object oHenchman)
{
    object oMaster = GetMaster(oHenchman);
    if (!GetIsObjectValid(oMaster)) return;
    AssignCommand(oHenchman, ClearAllActions());
    RemoveHenchman(oMaster, oHenchman);
    if (GetIsObjectValid(oHenchman)) ChangeToStandardFaction(oHenchman, STANDARD_FACTION_COMMONER);
}

// Send a stock associate-AI order ("HENCHMAN_CMD_FOLLOW", "HENCHMAN_CMD_STANDGROUND") from oPC.
void CMP_Order(object oPC, string sCommand)
{
    if (GetIsObjectValid(oPC)) AssignCommand(oPC, SpeakString(sCommand, TALKVOLUME_SILENT_SHOUT));
}
`;
}

const SCRIPTS: Record<string, string> = {
  c_hen_free: `// c_hen_free: TRUE when this companion has no master (it can be recruited).
#include "inc_companion"

int StartingConditional()
{
    return !GetIsObjectValid(GetMaster(OBJECT_SELF));
}
`,
  c_hen_mine: `// c_hen_mine: TRUE when the speaking PC leads this companion.
#include "inc_sim"

int StartingConditional()
{
    object oMaster = GetMaster(OBJECT_SELF);
    return GetIsObjectValid(oMaster) && oMaster == SimSpeaker();
}
`,
  c_hen_full: `// c_hen_full: TRUE when this companion is free but the speaker's party already has the maximum.
#include "inc_companion"

int StartingConditional()
{
    if (GetIsObjectValid(GetMaster(OBJECT_SELF))) return FALSE;
    return !CMP_PartyHasRoom(SimSpeaker());
}
`,
  a_hen_join: `// a_hen_join: recruit the speaking companion. Levelling, gear and spells were done at spawn.
#include "inc_companion"

void main()
{
    CMP_Join(OBJECT_SELF, SimSpeaker());
}
`,
  a_hen_leave: `// a_hen_leave: dismiss the speaking companion.
#include "inc_companion"

void main()
{
    CMP_Leave(OBJECT_SELF);
}
`,
  a_hen_stay: `// a_hen_stay: order the speaker's companions to hold position.
#include "inc_companion"

void main()
{
    CMP_Order(SimSpeaker(), "HENCHMAN_CMD_STANDGROUND");
}
`,
  a_hen_follow: `// a_hen_follow: order the speaker's companions to follow.
#include "inc_companion"

void main()
{
    CMP_Order(SimSpeaker(), "HENCHMAN_CMD_FOLLOW");
}
`,
};

/** Source for every companion script, keyed by resref, include first. */
export function generateCompanionScripts(opts: CompanionScriptOptions = {}): Record<string, string> {
  const max = Math.max(1, Math.min(10, Math.floor(opts.maxCompanions ?? DEFAULT_MAX_COMPANIONS)));
  const out: Record<string, string> = { [SIM_INCLUDE]: generateSimInclude(), [COMPANION_INCLUDE]: include(max) };
  for (const name of COMPANION_SCRIPTS) if (name !== COMPANION_INCLUDE) out[name] = withSimResult(SCRIPTS[name]);
  return out;
}

// --- Companion dialog

export interface DialogNode {
  speaker: "npc" | "pc";
  text: string;
  script?: string;
  condition?: string;
  /** Ends the conversation on purpose (skipped by the return-to-hub rule). */
  end?: boolean;
  children?: DialogNode[];
}

export interface CompanionDialogText {
  /** First meeting (free, party has room): who they are and why they are here. Required. */
  introduction: string;
  /** Answer to "Tell me about yourself". Required. */
  backstory: string;
  /** NPC line when they agree to join. */
  accept?: string;
  /** NPC line when they are free but the party is full. */
  partyFull?: string;
  /** NPC greeting when the speaker already leads them. */
  inParty?: string;
  /** NPC line when dismissed. */
  farewell?: string;
  /** NPC reply to the hold-position order. */
  stay?: string;
  /** NPC reply to the follow order. */
  follow?: string;
  /** NPC line for anyone else (e.g. another PC's companion). */
  fallback?: string;
  /** PC line asking them to join. */
  askToJoin?: string;
}

/**
 * The four-root companion dialog. Roots are evaluated in order and the first TRUE condition wins:
 * in the speaker's party → free but party full → free → fallback (always TRUE, so it never opens empty).
 */
export function buildCompanionDialogTree(t: CompanionDialogText): DialogNode[] {
  const backstory = (children: DialogNode[]): DialogNode => ({
    speaker: "pc",
    text: "Tell me about yourself.",
    children: [{ speaker: "npc", text: t.backstory, children }],
  });
  const goodbye: DialogNode = { speaker: "pc", text: "Another time." };
  const join: DialogNode = {
    speaker: "pc",
    text: t.askToJoin ?? "Will you travel with me?",
    children: [{ speaker: "npc", text: t.accept ?? "I'll come with you.", script: "a_hen_join", end: true }],
  };
  return [
    {
      speaker: "npc",
      text: t.inParty ?? "What do you need?",
      condition: "c_hen_mine",
      children: [
        {
          speaker: "pc",
          text: "Hold this position.",
          children: [{ speaker: "npc", text: t.stay ?? "I'll hold here.", script: "a_hen_stay" }],
        },
        {
          speaker: "pc",
          text: "Stay close to me.",
          children: [{ speaker: "npc", text: t.follow ?? "Right behind you.", script: "a_hen_follow" }],
        },
        {
          speaker: "pc",
          text: "We should part ways.",
          children: [{ speaker: "npc", text: t.farewell ?? "Until next time.", script: "a_hen_leave", end: true }],
        },
        { speaker: "pc", text: "Never mind." },
      ],
    },
    {
      speaker: "npc",
      text: t.partyFull ?? "You've already got all the help you need. Find me if that changes.",
      condition: "c_hen_full",
      children: [backstory([goodbye]), goodbye],
    },
    {
      speaker: "npc",
      text: t.introduction,
      condition: "c_hen_free",
      children: [backstory([join, goodbye]), join, goodbye],
    },
    { speaker: "npc", text: t.fallback ?? "I have nothing to say to you." },
  ];
}
