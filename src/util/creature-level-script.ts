/**
 * Generator for inc_cre_level.nss — spawn-time creature levelling (creature forge,
 * docs/creature-forge-spec.md §8.3) — and its single OnSpawn wrapper, cf_spawn.nss.
 *
 * Every engine behaviour this relies on was confirmed on a live NWN:EE server on
 * 2026-11-07 (spec §11 spike results): LevelUpHenchman adds every automatic class
 * feat and no illegal feat from a valid level-1 build; ObjectToJson(o, TRUE) ->
 * JsonToObject(..., TRUE) keeps tag, locals, HP and effects while replacing
 * SpecAbilityList; each ready SpecAbilityList entry is one cast and its
 * SpellCasterLevel is the caster level the spell uses; GetItemACValue is torso base
 * AC plus enhancement; base-game stores can be listed and copied from without
 * depleting them; and the engine refuses to equip items a creature isn't
 * proficient with (so the shopper filters on proficiency).
 */

import { STARTING_GOLD_LEVEL_1, WEALTH_BY_LEVEL } from "./wealth.js";

export const CREATURE_LEVEL_INCLUDE = "inc_cre_level";
export const CREATURE_LEVEL_WRAPPER = "cf_spawn";

/** Base-game stores used when a module names none (weapons/armor, general goods, magic items, temple). */
export const DEFAULT_GEAR_STORES = ["nw_storeweap001", "nw_storgenral001", "nw_storemagic001", "nw_storetmple001"];

export interface CreatureLevelOptions {
  /** Store tags or resrefs NPCs may buy from. Default: DEFAULT_GEAR_STORES. */
  stores?: string[];
  /** Whether bought gear can drop as loot (default true, the project's equipment convention). */
  droppable?: boolean;
}

function wealthFunctionBody(): string {
  const lines = [`    if (nLevel <= 1) return ${STARTING_GOLD_LEVEL_1};`];
  for (let level = 2; level < WEALTH_BY_LEVEL.length - 1; level++) {
    lines.push(`    if (nLevel == ${level}) return ${WEALTH_BY_LEVEL[level]};`);
  }
  lines.push(`    return ${WEALTH_BY_LEVEL[WEALTH_BY_LEVEL.length - 1]};`);
  return lines.join("\n");
}

export function generateCreatureLevelInclude(options: CreatureLevelOptions = {}): string {
  const storeList = (options.stores && options.stores.length > 0 ? options.stores : DEFAULT_GEAR_STORES)
    .map((s) => s.trim().toLowerCase())
    .filter((s) => /^[a-z0-9_]{1,16}$/.test(s));
  const stores = storeList.join(",");
  const droppable = options.droppable ?? true;
  const wealthBody = wealthFunctionBody();
  return `// inc_cre_level — spawn-time creature levelling (creature forge, docs/creature-forge-spec.md §8.3).
// Generated by nwn-mcp create_creature_level_system; regenerate rather than hand-edit.
//
// A creature built by forge_creature is a valid level-1 build carrying:
//   MCP_LEVEL (int)          absolute target level
//   MCP_LEVEL_REL (int)      offset from the party's average level (used if MCP_LEVEL is 0)
//   MCP_LEVEL_MIN/MAX (int)  clamp
//   MCP_LEVEL_PLAN (string)  comma list of class ids, one per level (blank = keep class)
//   MCP_SA_POOL (string)     JSON {"<class>": {"<spell level>": [spell ids, seeded order]}}
//   MCP_GEAR_WEALTH (float)  gear allowance multiplier; 0 = keep current gear
//   MCP_GEAR_ROLE (string)   pc | elite | standard | mook
//   MCP_GEAR_WEAPONS (string) comma list of preferred baseitems.2da rows
//   MCP_SA_PINNED (string)   comma list of spells.2da rows always picked first at their level
//   MCP_SA_DOMAIN (string)   JSON {"<class>": {"<spell level>": [domain spell ids]}}; one fills a slot per level
//   MCP_DOMAINS (string)     JSON {"<class>": [domain1, domain2]} (domains.2da rows), checked in game
// At spawn it: levels up with LevelUpHenchman, buys gear from the module's stores,
// rebuilds once (ObjectToJson/JsonToObject, state kept) to write spell abilities at
// the right caster level and slot count, then verifies and logs [SPEC_OK]/[SPEC_FAIL].
// Every purchase is logged as one [CL_LOOT] line per creature (and kept in MCP_GEAR_LOG)
// so the rewards phase can see what each creature will drop.

const string CL_STORES = "${stores}";
const int CL_DROPPABLE = ${droppable ? 1 : 0};
const string CL_LOG = "[CL]";

// ---- small helpers ----

void CL_Log(string sMsg)
{
    WriteTimestampedLogEntry(CL_LOG + " " + sMsg);
}

void CL_Spec(object oCreature, int bOk, string sField, string sExpected, string sActual)
{
    WriteTimestampedLogEntry((bOk ? "[SPEC_OK]" : "[SPEC_FAIL]") + " tag=" + GetTag(oCreature)
        + " field=" + sField + " expected=" + sExpected + " actual=" + sActual);
}

int CL_Cell(string s2DA, string sColumn, int nRow)
{
    string sValue = Get2DAString(s2DA, sColumn, nRow);
    if (sValue == "" || sValue == "****") return -1;
    return StringToInt(sValue);
}

// Token nIndex (0-based) of a comma list, or "" past the end.
string CL_Token(string sList, int nIndex)
{
    int nStart = 0;
    int i;
    for (i = 0; i < nIndex; i++)
    {
        int nComma = FindSubString(sList, ",", nStart);
        if (nComma < 0) return "";
        nStart = nComma + 1;
    }
    int nEnd = FindSubString(sList, ",", nStart);
    if (nEnd < 0) nEnd = GetStringLength(sList);
    return GetSubString(sList, nStart, nEnd - nStart);
}

int CL_ListHas(string sList, int nValue)
{
    return FindSubString("," + sList + ",", "," + IntToString(nValue) + ",") >= 0;
}

// DMG wealth by level (wealth.ts WEALTH_BY_LEVEL; level 1 = STARTING_GOLD_LEVEL_1).
int CL_Wealth(int nLevel)
{
${wealthBody}
}

float CL_RoleShare(string sRole)
{
    if (sRole == "standard") return 0.5;
    if (sRole == "mook") return 0.25;
    return 1.0;
}

// ---- target level ----

int CL_TargetLevel(object oCreature)
{
    int nTarget = GetLocalInt(oCreature, "MCP_LEVEL");
    if (nTarget <= 0)
    {
        int nSum = 0;
        int nCount = 0;
        object oPC = GetFirstPC();
        while (GetIsObjectValid(oPC))
        {
            if (!GetIsDM(oPC)) { nSum += GetHitDice(oPC); nCount++; }
            oPC = GetNextPC();
        }
        int nBase = nCount > 0 ? nSum / nCount : 1;
        nTarget = nBase + GetLocalInt(oCreature, "MCP_LEVEL_REL");
    }
    int nMin = GetLocalInt(oCreature, "MCP_LEVEL_MIN");
    int nMax = GetLocalInt(oCreature, "MCP_LEVEL_MAX");
    if (nMax <= 0) nMax = 40;
    if (nTarget < nMin) nTarget = nMin;
    if (nTarget > nMax) nTarget = nMax;
    if (nTarget < 1) nTarget = 1;
    return nTarget;
}

// ---- proficiency (engine refuses to equip items without it) ----

int CL_ArmorBaseAC(object oItem)
{
    int nTorso = GetItemAppearance(oItem, ITEM_APPR_TYPE_ARMOR_MODEL, ITEM_APPR_ARMOR_MODEL_TORSO);
    return FloatToInt(StringToFloat(Get2DAString("parts_chest", "ACBONUS", nTorso)) + 0.5);
}

int CL_CanUse(object oCreature, object oItem)
{
    if (GetItemHasItemProperty(oItem, ITEM_PROPERTY_USE_LIMITATION_CLASS)
        || GetItemHasItemProperty(oItem, ITEM_PROPERTY_USE_LIMITATION_RACIAL_TYPE)
        || GetItemHasItemProperty(oItem, ITEM_PROPERTY_USE_LIMITATION_ALIGNMENT_GROUP)
        || GetItemHasItemProperty(oItem, ITEM_PROPERTY_USE_LIMITATION_SPECIFIC_ALIGNMENT))
        return FALSE;
    int nBase = GetBaseItemType(oItem);
    if (nBase == BASE_ITEM_ARMOR)
    {
        int nAC = CL_ArmorBaseAC(oItem);
        if (nAC <= 0) return TRUE;
        if (nAC <= 3) return GetHasFeat(FEAT_ARMOR_PROFICIENCY_LIGHT, oCreature);
        if (nAC <= 5) return GetHasFeat(FEAT_ARMOR_PROFICIENCY_MEDIUM, oCreature);
        return GetHasFeat(FEAT_ARMOR_PROFICIENCY_HEAVY, oCreature);
    }
    int bNeeds = FALSE;
    int i;
    for (i = 0; i <= 4; i++)
    {
        int nFeat = CL_Cell("baseitems", "ReqFeat" + IntToString(i), nBase);
        if (nFeat >= 0)
        {
            bNeeds = TRUE;
            if (GetHasFeat(nFeat, oCreature)) return TRUE;
        }
    }
    return !bNeeds;
}

// Parses a baseitems.2da hex cell such as "0x1C030".
int CL_Hex(string sHex)
{
    string sDigits = "0123456789abcdef";
    string sLower = GetStringLowerCase(sHex);
    int nStart = GetStringLeft(sLower, 2) == "0x" ? 2 : 0;
    int nValue = 0;
    int i;
    for (i = nStart; i < GetStringLength(sLower); i++)
    {
        int nDigit = FindSubString(sDigits, GetSubString(sLower, i, 1));
        if (nDigit < 0) return nValue;
        nValue = nValue * 16 + nDigit;
    }
    return nValue;
}

// baseitems.2da EquipableSlots bits match INVENTORY_SLOT_* indices (0x10 = right hand, slot 4).
int CL_FitsSlot(object oItem, int nSlot)
{
    int nMask = CL_Hex(Get2DAString("baseitems", "EquipableSlots", GetBaseItemType(oItem)));
    return (nMask & (1 << nSlot)) != 0;
}

// ---- stores ----

object CL_Store(string sName, location lWhere)
{
    object oStore = GetObjectByTag(sName);
    if (GetIsObjectValid(oStore) && GetObjectType(oStore) == OBJECT_TYPE_STORE) return oStore;
    oStore = GetLocalObject(GetModule(), "MCP_STORE_" + sName);
    if (GetIsObjectValid(oStore)) return oStore;
    oStore = CreateObject(OBJECT_TYPE_STORE, sName, lWhere, FALSE, "mcp_gear_" + sName);
    if (GetIsObjectValid(oStore)) SetLocalObject(GetModule(), "MCP_STORE_" + sName, oStore);
    else CL_Log("store not found: " + sName);
    return oStore;
}

int CL_HasFocus(object oCreature, int nBase)
{
    int nFocus = CL_Cell("baseitems", "WeaponFocusFeat", nBase);
    return nFocus >= 0 && GetHasFeat(nFocus, oCreature);
}

// Best affordable, usable item for a slot across all stores (highest score, then price).
// nKind: 0 armor, 1 weapon, 2 shield, 3 ammo, 4 accessory, 5 melee backup (any usable melee weapon).
object CL_Pick(object oCreature, int nSlot, int nKind, int nBudget, int nAmmoBase)
{
    object oBest = OBJECT_INVALID;
    int nBestScore = -1;
    string sWeapons = GetLocalString(oCreature, "MCP_GEAR_WEAPONS");
    int nStore = 0;
    string sName = CL_Token(CL_STORES, 0);
    while (sName != "")
    {
        object oStore = CL_Store(sName, GetLocation(oCreature));
        object oItem = GetFirstItemInInventory(oStore);
        while (GetIsObjectValid(oItem))
        {
            int nBase = GetBaseItemType(oItem);
            int nPrice = GetGoldPieceValue(oItem);
            if (nKind == 3) nPrice = nPrice / (GetItemStackSize(oItem) > 0 ? GetItemStackSize(oItem) : 1) * 24;
            int bShield = nBase == BASE_ITEM_SMALLSHIELD || nBase == BASE_ITEM_LARGESHIELD || nBase == BASE_ITEM_TOWERSHIELD;
            int bKind = FALSE;
            if (nPrice <= nBudget)
            {
                if (nKind == 0) bKind = nBase == BASE_ITEM_ARMOR;
                else if (nKind == 2) bKind = bShield;
                else if (nKind == 3) bKind = nBase == nAmmoBase;
                else if (nKind == 5) bKind = !bShield && nBase != BASE_ITEM_ARMOR && nBase != BASE_ITEM_TORCH
                    && nBase != BASE_ITEM_MAGICWAND && nBase != BASE_ITEM_MAGICROD && nBase != BASE_ITEM_MAGICSTAFF
                    && CL_Cell("baseitems", "RangedWeapon", nBase) < 0;
                else if (nKind == 1) bKind = !bShield && nBase != BASE_ITEM_ARMOR && nBase != BASE_ITEM_TORCH
                    && nBase != BASE_ITEM_MAGICWAND && nBase != BASE_ITEM_MAGICROD && nBase != BASE_ITEM_MAGICSTAFF
                    && (sWeapons == "" || CL_ListHas(sWeapons, nBase) || CL_HasFocus(oCreature, nBase));
                else bKind = nBase != BASE_ITEM_ARMOR && !bShield;
            }
            if (bKind && CL_FitsSlot(oItem, nSlot) && (nKind != 4 || !CL_FitsSlot(oItem, INVENTORY_SLOT_RIGHTHAND))
                && CL_CanUse(oCreature, oItem))
            {
                int nScore = 0;
                if (nKind == 0) nScore = CL_ArmorBaseAC(oItem);
                else if (nKind == 1) nScore = (CL_HasFocus(oCreature, nBase) ? 2 : 0) + (CL_ListHas(sWeapons, nBase) ? 1 : 0);
                int nTotal = nScore * 1000000 + nPrice;
                if (nTotal > nBestScore) { nBestScore = nTotal; oBest = oItem; }
            }
            oItem = GetNextItemInInventory(oStore);
        }
        nStore++;
        sName = CL_Token(CL_STORES, nStore);
    }
    return oBest;
}

// Copy a store item onto the creature and equip it into nSlot (nSlot < 0: keep it in the
// inventory unequipped). Records the purchase in MCP_GEAR_LOG. Returns the price paid.
int CL_Buy(object oCreature, object oStoreItem, int nSlot, int nStack)
{
    if (!GetIsObjectValid(oStoreItem)) return 0;
    int nPrice = GetGoldPieceValue(oStoreItem);
    object oOld = nSlot >= 0 ? GetItemInSlot(nSlot, oCreature) : OBJECT_INVALID;
    object oItem = CopyItem(oStoreItem, oCreature, TRUE);
    if (!GetIsObjectValid(oItem)) return 0;
    if (nStack > 0)
    {
        nPrice = nPrice / (GetItemStackSize(oItem) > 0 ? GetItemStackSize(oItem) : 1) * nStack;
        SetItemStackSize(oItem, nStack);
    }
    SetIdentified(oItem, TRUE);
    SetDroppableFlag(oItem, CL_DROPPABLE);
    if (GetIsObjectValid(oOld)) DestroyObject(oOld);
    if (nSlot >= 0) AssignCommand(oCreature, ActionEquipItem(oItem, nSlot));
    string sEntry = GetResRef(oItem) + "@" + (nSlot >= 0 ? IntToString(nSlot) : "inv")
        + (nStack > 0 ? "x" + IntToString(nStack) : "") + ":" + IntToString(nPrice);
    string sLog = GetLocalString(oCreature, "MCP_GEAR_LOG");
    SetLocalString(oCreature, "MCP_GEAR_LOG", sLog == "" ? sEntry : sLog + "," + sEntry);
    return nPrice;
}

void CL_Finish(object oCreature);

// Gear is bought one slot per call (each scan of the stores gets its own instruction budget).
int CL_GearLeft(object oCreature, int nPercent)
{
    int nTotal = GetLocalInt(oCreature, "MCP_GEAR_TOTAL");
    int nLeft = nTotal - GetLocalInt(oCreature, "MCP_GEAR_SPENT");
    int nShare = nPercent > 0 ? nTotal * nPercent / 100 : nLeft;
    return nShare < nLeft ? nShare : nLeft;
}

void CL_GearSpend(object oCreature, int nPrice)
{
    SetLocalInt(oCreature, "MCP_GEAR_SPENT", GetLocalInt(oCreature, "MCP_GEAR_SPENT") + nPrice);
}

void CL_GearDone(object oCreature)
{
    if (!GetIsObjectValid(oCreature)) return;
    // Unspent allowance is discarded: the creature is never given the difference as gold.
    SetLocalInt(oCreature, "MCP_GOLD_AFTER_GEAR", GetGold(oCreature));
    CL_Log(GetTag(oCreature) + " gear spent=" + IntToString(GetLocalInt(oCreature, "MCP_GEAR_SPENT"))
        + "/" + IntToString(GetLocalInt(oCreature, "MCP_GEAR_TOTAL")));
    // One line per creature for the rewards phase: resref@slot[xstack]:gp, slot = INVENTORY_SLOT_* or "inv".
    WriteTimestampedLogEntry("[CL_LOOT] tag=" + GetTag(oCreature) + " resref=" + GetResRef(oCreature)
        + " area=" + GetTag(GetArea(oCreature)) + " droppable=" + IntToString(CL_DROPPABLE)
        + " items=" + GetLocalString(oCreature, "MCP_GEAR_LOG"));
    // Equipping is queued as actions; give them time before the rebuild snapshots the creature.
    DelayCommand(2.0, CL_Finish(oCreature));
}

void CL_GearAccessory(object oCreature, int nStep)
{
    if (!GetIsObjectValid(oCreature)) return;
    if (nStep >= 8 || CL_GearLeft(oCreature, 0) <= 0) { CL_GearDone(oCreature); return; }
    int nSlot = nStep == 0 ? INVENTORY_SLOT_NECK : nStep == 1 ? INVENTORY_SLOT_CLOAK : nStep == 2 ? INVENTORY_SLOT_BELT
        : nStep == 3 ? INVENTORY_SLOT_BOOTS : nStep == 4 ? INVENTORY_SLOT_RIGHTRING : nStep == 5 ? INVENTORY_SLOT_LEFTRING
        : nStep == 6 ? INVENTORY_SLOT_ARMS : INVENTORY_SLOT_HEAD;
    if (!GetIsObjectValid(GetItemInSlot(nSlot, oCreature)))
        CL_GearSpend(oCreature, CL_Buy(oCreature, CL_Pick(oCreature, nSlot, 4, CL_GearLeft(oCreature, 0), 0), nSlot, 0));
    DelayCommand(0.1, CL_GearAccessory(oCreature, nStep + 1));
}

void CL_GearOffhand(object oCreature)
{
    if (!GetIsObjectValid(oCreature)) return;
    object oWeapon = GetItemInSlot(INVENTORY_SLOT_RIGHTHAND, oCreature);
    int nWeaponBase = GetIsObjectValid(oWeapon) ? GetBaseItemType(oWeapon) : -1;
    int bRanged = nWeaponBase >= 0 && CL_Cell("baseitems", "RangedWeapon", nWeaponBase) >= 0;
    int nAmmoType = nWeaponBase >= 0 ? CL_Cell("baseitems", "AmmunitionType", nWeaponBase) : -1;
    if (bRanged && nAmmoType >= 1 && nAmmoType <= 3)
    {
        int nAmmoBase = nAmmoType == 1 ? BASE_ITEM_ARROW : nAmmoType == 2 ? BASE_ITEM_BOLT : BASE_ITEM_BULLET;
        int nAmmoSlot = nAmmoType == 1 ? INVENTORY_SLOT_ARROWS : nAmmoType == 2 ? INVENTORY_SLOT_BOLTS : INVENTORY_SLOT_BULLETS;
        int nCount = nAmmoType == 3 ? 15 : 24;
        CL_GearSpend(oCreature, CL_Buy(oCreature, CL_Pick(oCreature, nAmmoSlot, 3, CL_GearLeft(oCreature, 10), nAmmoBase), nAmmoSlot, nCount));
    }
    if (bRanged)
    {
        // The stock AI switches to melee when ammo runs out, but only if a melee weapon is in
        // the inventory. Always buy one (5% of the allowance, at least 15 gp if any is left).
        int nBackup = CL_GearLeft(oCreature, 5);
        int nLeft = CL_GearLeft(oCreature, 0);
        if (nBackup < 15) nBackup = nLeft < 15 ? nLeft : 15;
        object oBackup = CL_Pick(oCreature, INVENTORY_SLOT_RIGHTHAND, 5, nBackup, 0);
        if (GetIsObjectValid(oBackup))
        {
            SetLocalString(oCreature, "MCP_GEAR_BACKUP", GetResRef(oBackup));
            CL_GearSpend(oCreature, CL_Buy(oCreature, oBackup, -1, 0));
        }
        else SetLocalString(oCreature, "MCP_GEAR_BACKUP", "none");
    }
    else if (nWeaponBase >= 0 && !bRanged
        && CL_Cell("baseitems", "WeaponSize", nWeaponBase) <= GetCreatureSize(oCreature)
        && GetHasFeat(FEAT_SHIELD_PROFICIENCY, oCreature))
    {
        CL_GearSpend(oCreature, CL_Buy(oCreature, CL_Pick(oCreature, INVENTORY_SLOT_LEFTHAND, 2, CL_GearLeft(oCreature, 10), 0), INVENTORY_SLOT_LEFTHAND, 0));
    }
    DelayCommand(0.1, CL_GearAccessory(oCreature, 0));
}

int CL_WantsWeapon(object oCreature)
{
    return !(GetLevelByClass(CLASS_TYPE_MONK, oCreature) > 0 && GetLocalString(oCreature, "MCP_GEAR_WEAPONS") == "");
}

void CL_GearWeapon(object oCreature)
{
    if (!GetIsObjectValid(oCreature)) return;
    if (CL_WantsWeapon(oCreature))
        CL_GearSpend(oCreature, CL_Buy(oCreature, CL_Pick(oCreature, INVENTORY_SLOT_RIGHTHAND, 1, CL_GearLeft(oCreature, 35), 0), INVENTORY_SLOT_RIGHTHAND, 0));
    // The off-hand choice depends on the equipped weapon, so wait for the equip action.
    DelayCommand(1.0, CL_GearOffhand(oCreature));
}

void CL_Gear(object oCreature)
{
    float fWealth = GetLocalFloat(oCreature, "MCP_GEAR_WEALTH");
    SetLocalInt(oCreature, "MCP_GOLD_BEFORE", GetGold(oCreature));
    if (fWealth <= 0.0) { CL_GearDone(oCreature); return; }
    int nLevel = GetHitDice(oCreature);
    SetLocalInt(oCreature, "MCP_GEAR_TOTAL",
        FloatToInt(IntToFloat(CL_Wealth(nLevel)) * CL_RoleShare(GetLocalString(oCreature, "MCP_GEAR_ROLE")) * fWealth));
    SetLocalInt(oCreature, "MCP_GEAR_SPENT", 0);
    CL_GearSpend(oCreature, CL_Buy(oCreature, CL_Pick(oCreature, INVENTORY_SLOT_CHEST, 0, CL_GearLeft(oCreature, 30), 0), INVENTORY_SLOT_CHEST, 0));
    DelayCommand(0.1, CL_GearWeapon(oCreature));
}

// ---- spell abilities ----

int CL_BonusSpells(int nMod, int nSpellLevel)
{
    if (nSpellLevel < 1 || nMod < nSpellLevel) return 0;
    return (nMod - nSpellLevel) / 4 + 1;
}

int CL_AbilityConst(string sAbil)
{
    if (sAbil == "STR") return ABILITY_STRENGTH;
    if (sAbil == "DEX") return ABILITY_DEXTERITY;
    if (sAbil == "CON") return ABILITY_CONSTITUTION;
    if (sAbil == "INT") return ABILITY_INTELLIGENCE;
    if (sAbil == "WIS") return ABILITY_WISDOM;
    return ABILITY_CHARISMA;
}

// Slots per day for one class at one spell level (-1 when the class can't cast it).
int CL_Slots(object oCreature, int nClass, int nClassLevel, int nSpellLevel)
{
    string sGain = Get2DAString("classes", "SpellGainTable", nClass);
    if (sGain == "" || sGain == "****") return -1;
    int nBase = CL_Cell(sGain, "SpellLevel" + IntToString(nSpellLevel), nClassLevel - 1);
    if (nBase < 0) return -1;
    int nMod = GetAbilityModifier(CL_AbilityConst(Get2DAString("classes", "SpellcastingAbil", nClass)), oCreature);
    return nBase + CL_BonusSpells(nMod, nSpellLevel);
}

// Spell level of nSpell for one class: its domain level when it is one of that class's domain spells
// (jDom = the class's MCP_SA_DOMAIN object), else the class's spells.2da column; -1 when neither.
int CL_SpellLevel(json jDom, string sColumn, int nSpell)
{
    if (JsonGetType(jDom) == JSON_TYPE_OBJECT)
    {
        int nLevel;
        for (nLevel = 1; nLevel <= 9; nLevel++)
        {
            json jIds = JsonObjectGet(jDom, IntToString(nLevel));
            if (JsonGetType(jIds) == JSON_TYPE_ARRAY && JsonGetType(JsonFind(jIds, JsonInt(nSpell))) != JSON_TYPE_NULL) return nLevel;
        }
    }
    if (sColumn == "" || sColumn == "****") return -1;
    return CL_Cell("spells", sColumn, nSpell);
}

// Builds the SpecAbilityList JSON value and records the expected ready counts.
json CL_SpellEntries(object oCreature)
{
    json jDomains = JsonParse(GetLocalString(oCreature, "MCP_SA_DOMAIN"));
    json jEntries = JsonArray();
    json jPools = JsonParse(GetLocalString(oCreature, "MCP_SA_POOL"));
    string sExpect = "";
    int nPos;
    for (nPos = 1; nPos <= 3; nPos++)
    {
        int nClass = GetClassByPosition(nPos, oCreature);
        if (nClass == CLASS_TYPE_INVALID) continue;
        int nClassLevel = GetLevelByPosition(nPos, oCreature);
        json jPool = JsonObjectGet(jPools, IntToString(nClass));
        if (JsonGetType(jPool) != JSON_TYPE_OBJECT) continue;
        string sKnown = Get2DAString("classes", "SpellKnownTable", nClass);
        string sColumn = Get2DAString("classes", "SpellTableColumn", nClass);
        string sPinned = GetLocalString(oCreature, "MCP_SA_PINNED");
        json jDom = JsonObjectGet(jDomains, IntToString(nClass));
        int nSpellLevel;
        for (nSpellLevel = 0; nSpellLevel <= 9; nSpellLevel++)
        {
            int nSlots = CL_Slots(oCreature, nClass, nClassLevel, nSpellLevel);
            if (nSlots <= 0) continue;
            json jIds = JsonObjectGet(jPool, IntToString(nSpellLevel));
            int nPoolSize = JsonGetLength(jIds);
            if (nPoolSize <= 0) continue;
            int nDistinct = nSlots;
            if (sKnown != "" && sKnown != "****")
            {
                int nKnown = CL_Cell(sKnown, "SpellLevel" + IntToString(nSpellLevel), nClassLevel - 1);
                if (nKnown > 0 && nKnown < nDistinct) nDistinct = nKnown;
            }
            if (nDistinct > nPoolSize) nDistinct = nPoolSize;
            // Pinned spells first (those on this class's list at this spell level), then the
            // pool from a random start, skipping duplicates, until nDistinct spells are chosen.
            json jChosen = JsonArray();
            // The domain slot: one of this level's domain spells, before anything else.
            json jDomIds = JsonObjectGet(jDom, IntToString(nSpellLevel));
            if (JsonGetType(jDomIds) == JSON_TYPE_ARRAY && JsonGetLength(jDomIds) > 0)
                jChosen = JsonArrayInsert(jChosen, JsonArrayGet(jDomIds, Random(JsonGetLength(jDomIds))));
            int p = 0;
            string sPin = CL_Token(sPinned, 0);
            while (sPin != "" && JsonGetLength(jChosen) < nDistinct)
            {
                int nPin = StringToInt(sPin);
                if (CL_SpellLevel(jDom, sColumn, nPin) == nSpellLevel && JsonGetType(JsonFind(jChosen, JsonInt(nPin))) == JSON_TYPE_NULL)
                    jChosen = JsonArrayInsert(jChosen, JsonInt(nPin));
                p++;
                sPin = CL_Token(sPinned, p);
            }
            int nOffset = Random(nPoolSize);
            int k;
            for (k = 0; k < nPoolSize && JsonGetLength(jChosen) < nDistinct; k++)
            {
                json jId = JsonArrayGet(jIds, (nOffset + k) % nPoolSize);
                if (JsonGetType(JsonFind(jChosen, jId)) == JSON_TYPE_NULL) jChosen = JsonArrayInsert(jChosen, jId);
            }
            int nChosen = JsonGetLength(jChosen);
            for (k = 0; k < nSlots; k++)
            {
                int nSpell = JsonGetInt(JsonArrayGet(jChosen, k % nChosen));
                json jEntry = JsonObject();
                jEntry = JsonObjectSet(jEntry, "__struct_id", JsonInt(0));
                jEntry = JsonObjectSet(jEntry, "Spell", JsonParse("{\\"type\\":\\"word\\",\\"value\\":" + IntToString(nSpell) + "}"));
                jEntry = JsonObjectSet(jEntry, "SpellCasterLevel", JsonParse("{\\"type\\":\\"byte\\",\\"value\\":" + IntToString(nClassLevel) + "}"));
                jEntry = JsonObjectSet(jEntry, "SpellFlags", JsonParse("{\\"type\\":\\"byte\\",\\"value\\":1}"));
                jEntries = JsonArrayInsert(jEntries, jEntry);
            }
            sExpect += IntToString(nClass) + ":" + IntToString(nSpellLevel) + "=" + IntToString(nSlots) + ";";
        }
    }
    SetLocalString(oCreature, "MCP_SA_EXPECT", sExpect);
    return jEntries;
}

// ---- verification (runs on the final object) ----

// Domains: the class entry carries the planned domains, and the creature has each domain's power feat.
void CL_VerifyDomains(object oCreature)
{
    json jPlan = JsonParse(GetLocalString(oCreature, "MCP_DOMAINS"));
    if (JsonGetType(jPlan) != JSON_TYPE_OBJECT) return;
    int nPos;
    for (nPos = 1; nPos <= 3; nPos++)
    {
        int nClass = GetClassByPosition(nPos, oCreature);
        if (nClass == CLASS_TYPE_INVALID) continue;
        json jPair = JsonObjectGet(jPlan, IntToString(nClass));
        if (JsonGetType(jPair) != JSON_TYPE_ARRAY) continue;
        int nD1 = JsonGetInt(JsonArrayGet(jPair, 0));
        int nD2 = JsonGetInt(JsonArrayGet(jPair, 1));
        string sExpected = IntToString(nD1) + "," + IntToString(nD2);
        string sActual = IntToString(GetDomain(oCreature, 1, nClass)) + "," + IntToString(GetDomain(oCreature, 2, nClass));
        CL_Spec(oCreature, sActual == sExpected, "cl_domain_" + IntToString(nClass), sExpected, sActual);
        int nF1 = CL_Cell("domains", "GrantedFeat", nD1);
        int nF2 = CL_Cell("domains", "GrantedFeat", nD2);
        int bFeats = (nF1 < 0 || GetHasFeat(nF1, oCreature)) && (nF2 < 0 || GetHasFeat(nF2, oCreature));
        CL_Spec(oCreature, bFeats, "cl_domain_feats_" + IntToString(nClass),
            IntToString(nF1) + "," + IntToString(nF2), bFeats ? "present" : "missing");
    }
}

// Domain spells: at every spell level with domain spells and slots, at least one ready ability is one of them.
void CL_VerifyDomainSpells(object oCreature, json jDomains, int nCount)
{
    if (JsonGetType(jDomains) != JSON_TYPE_OBJECT) return;
    int nPos;
    for (nPos = 1; nPos <= 3; nPos++)
    {
        int nClass = GetClassByPosition(nPos, oCreature);
        if (nClass == CLASS_TYPE_INVALID) continue;
        json jDom = JsonObjectGet(jDomains, IntToString(nClass));
        if (JsonGetType(jDom) != JSON_TYPE_OBJECT) continue;
        string sExpected = "";
        string sActual = "";
        int nLevel;
        for (nLevel = 1; nLevel <= 9; nLevel++)
        {
            json jIds = JsonObjectGet(jDom, IntToString(nLevel));
            if (JsonGetType(jIds) != JSON_TYPE_ARRAY || JsonGetLength(jIds) == 0) continue;
            if (CL_Slots(oCreature, nClass, GetLevelByPosition(nPos, oCreature), nLevel) <= 0) continue;
            sExpected += IntToString(nLevel) + ";";
            int i;
            for (i = 0; i < nCount; i++)
            {
                if (!GetSpellAbilityReady(oCreature, i)) continue;
                if (JsonGetType(JsonFind(jIds, JsonInt(GetSpellAbilitySpell(oCreature, i)))) == JSON_TYPE_NULL) continue;
                sActual += IntToString(nLevel) + ";";
                break;
            }
        }
        if (sExpected != "") CL_Spec(oCreature, sActual == sExpected, "cl_spell_domain_" + IntToString(nClass), sExpected, sActual);
    }
}

void CL_Verify(object oCreature)
{
    if (!GetIsObjectValid(oCreature)) return;
    DeleteLocalInt(oCreature, "MCP_CL_VERIFY");
    int nTarget = GetLocalInt(oCreature, "MCP_LEVEL_TARGET");
    CL_Spec(oCreature, GetHitDice(oCreature) == nTarget, "cl_level", IntToString(nTarget), IntToString(GetHitDice(oCreature)));

    // Planned class per level, collapsed to final class levels.
    string sPlan = GetLocalString(oCreature, "MCP_LEVEL_PLAN");
    if (sPlan != "")
    {
        int nPos;
        for (nPos = 1; nPos <= 3; nPos++)
        {
            int nClass = GetClassByPosition(nPos, oCreature);
            if (nClass == CLASS_TYPE_INVALID) continue;
            int nPlanned = 0;
            int i;
            for (i = 0; i < nTarget; i++) if (StringToInt(CL_Token(sPlan, i)) == nClass) nPlanned++;
            CL_Spec(oCreature, nPlanned == GetLevelByPosition(nPos, oCreature), "cl_class_" + IntToString(nClass),
                IntToString(nPlanned), IntToString(GetLevelByPosition(nPos, oCreature)));
        }
    }

    // Spell abilities: each on a class list at an accessible level, right caster level, right count.
    string sExpect = GetLocalString(oCreature, "MCP_SA_EXPECT");
    json jDomains = JsonParse(GetLocalString(oCreature, "MCP_SA_DOMAIN"));
    if (sExpect != "")
    {
        int nCount = GetSpellAbilityCount(oCreature);
        int nBad = 0;
        string sActual = "";
        int nPos;
        for (nPos = 1; nPos <= 3; nPos++)
        {
            int nClass = GetClassByPosition(nPos, oCreature);
            if (nClass == CLASS_TYPE_INVALID) continue;
            int nClassLevel = GetLevelByPosition(nPos, oCreature);
            string sColumn = Get2DAString("classes", "SpellTableColumn", nClass);
            if (sColumn == "" || sColumn == "****") continue;
            json jDom = JsonObjectGet(jDomains, IntToString(nClass));
            int nSpellLevel;
            for (nSpellLevel = 0; nSpellLevel <= 9; nSpellLevel++)
            {
                int nReady = 0;
                int i;
                for (i = 0; i < nCount; i++)
                {
                    int nSpell = GetSpellAbilitySpell(oCreature, i);
                    if (CL_SpellLevel(jDom, sColumn, nSpell) != nSpellLevel) continue;
                    if (!GetSpellAbilityReady(oCreature, i)) continue;
                    if (GetSpellAbilityCasterLevel(oCreature, i) != nClassLevel) nBad++;
                    nReady++;
                }
                if (nReady > 0) sActual += IntToString(nClass) + ":" + IntToString(nSpellLevel) + "=" + IntToString(nReady) + ";";
            }
        }
        for (nPos = 0; nPos < nCount; nPos++)
        {
            int nSpell = GetSpellAbilitySpell(oCreature, nPos);
            int bOnList = FALSE;
            int c;
            for (c = 1; c <= 3; c++)
            {
                int nClass = GetClassByPosition(c, oCreature);
                if (nClass == CLASS_TYPE_INVALID) continue;
                string sColumn = Get2DAString("classes", "SpellTableColumn", nClass);
                int nLevel = CL_SpellLevel(JsonObjectGet(jDomains, IntToString(nClass)), sColumn, nSpell);
                if (nLevel >= 0 && CL_Slots(oCreature, nClass, GetLevelByPosition(c, oCreature), nLevel) > 0) bOnList = TRUE;
            }
            if (!bOnList) nBad++;
        }
        CL_Spec(oCreature, sActual == sExpect, "cl_spell_slots", sExpect, sActual);
        string sPinned = GetLocalString(oCreature, "MCP_SA_PINNED");
        int p = 0;
        string sPin = CL_Token(sPinned, 0);
        while (sPin != "")
        {
            int bFound = FALSE;
            int i;
            for (i = 0; i < nCount; i++) if (GetSpellAbilitySpell(oCreature, i) == StringToInt(sPin)) bFound = TRUE;
            CL_Spec(oCreature, bFound, "cl_spell_pinned_" + sPin, "present", bFound ? "present" : "missing");
            p++;
            sPin = CL_Token(sPinned, p);
        }
        CL_Spec(oCreature, nBad == 0, "cl_spell_validity", "0", IntToString(nBad));
        CL_VerifyDomainSpells(oCreature, jDomains, nCount);
    }
    CL_VerifyDomains(oCreature);

    // Gear: everything the creature holds equipped is usable (the engine drops what isn't).
    if (GetLocalFloat(oCreature, "MCP_GEAR_WEALTH") > 0.0)
    {
        object oChest = GetItemInSlot(INVENTORY_SLOT_CHEST, oCreature);
        object oHand = GetItemInSlot(INVENTORY_SLOT_RIGHTHAND, oCreature);
        CL_Spec(oCreature, GetIsObjectValid(oChest), "cl_gear_chest", "equipped", GetResRef(oChest));
        if (CL_WantsWeapon(oCreature)) CL_Spec(oCreature, GetIsObjectValid(oHand), "cl_gear_weapon", "equipped", GetResRef(oHand));
        string sBackup = GetLocalString(oCreature, "MCP_GEAR_BACKUP");
        if (sBackup != "")
        {
            int bHas = FALSE;
            object oInv = GetFirstItemInInventory(oCreature);
            while (GetIsObjectValid(oInv))
            {
                if (GetResRef(oInv) == sBackup) bHas = TRUE;
                oInv = GetNextItemInInventory(oCreature);
            }
            CL_Spec(oCreature, bHas, "cl_gear_melee_backup", "melee_weapon_in_inventory", sBackup);
        }
        CL_Spec(oCreature, GetLocalInt(oCreature, "MCP_GOLD_AFTER_GEAR") == GetLocalInt(oCreature, "MCP_GOLD_BEFORE"),
            "cl_gear_no_gold", IntToString(GetLocalInt(oCreature, "MCP_GOLD_BEFORE")),
            IntToString(GetLocalInt(oCreature, "MCP_GOLD_AFTER_GEAR")));
        CL_Log(GetTag(oCreature) + " lvl=" + IntToString(GetHitDice(oCreature)) + " chest=" + GetResRef(oChest)
            + " ac=" + IntToString(GetAC(oCreature)) + " rh=" + GetResRef(oHand)
            + " lh=" + GetResRef(GetItemInSlot(INVENTORY_SLOT_LEFTHAND, oCreature))
            + " spent=" + IntToString(GetLocalInt(oCreature, "MCP_GEAR_SPENT")) + "/" + IntToString(GetLocalInt(oCreature, "MCP_GEAR_TOTAL")));
    }
}

// ---- finish: write spell abilities with a state-keeping rebuild ----

void CL_Finish(object oCreature)
{
    if (!GetIsObjectValid(oCreature)) return;
    SetLocalInt(oCreature, "MCP_LEVEL_DONE", 1);
    if (GetLocalString(oCreature, "MCP_SA_POOL") == "")
    {
        CL_Verify(oCreature);
        return;
    }
    json jEntries = CL_SpellEntries(oCreature);
    SetLocalInt(oCreature, "MCP_CL_VERIFY", 1);
    json jObj = ObjectToJson(oCreature, TRUE);
    json jList = JsonObject();
    jList = JsonObjectSet(jList, "type", JsonString("list"));
    jList = JsonObjectSet(jList, "value", jEntries);
    jObj = JsonObjectSet(jObj, "SpecAbilityList", jList);
    object oNew = JsonToObject(jObj, GetLocation(oCreature), OBJECT_INVALID, TRUE);
    if (!GetIsObjectValid(oNew))
    {
        CL_Log(GetTag(oCreature) + " rebuild failed; spell abilities not written");
        DeleteLocalInt(oCreature, "MCP_CL_VERIFY");
        CL_Verify(oCreature);
        return;
    }
    DestroyObject(oCreature);
}

// ---- levelling ----

void CL_LevelStep(object oCreature, int nTarget)
{
    if (!GetIsObjectValid(oCreature)) return;
    string sPlan = GetLocalString(oCreature, "MCP_LEVEL_PLAN");
    int nSteps = 0;
    while (GetHitDice(oCreature) < nTarget && nSteps < 4)
    {
        int nNext = GetHitDice(oCreature) + 1;
        string sClass = CL_Token(sPlan, nNext - 1);
        int nClass = sClass == "" ? CLASS_TYPE_INVALID : StringToInt(sClass);
        if (LevelUpHenchman(oCreature, nClass, TRUE, PACKAGE_INVALID) == 0)
        {
            CL_Log(GetTag(oCreature) + " LevelUpHenchman refused level " + IntToString(nNext)
                + " class " + IntToString(nClass) + "; stopping at " + IntToString(GetHitDice(oCreature)));
            nTarget = GetHitDice(oCreature);
            break;
        }
        nSteps++;
    }
    if (GetHitDice(oCreature) < nTarget)
    {
        DelayCommand(0.1, CL_LevelStep(oCreature, nTarget));
        return;
    }
    SetLocalInt(oCreature, "MCP_LEVEL_TARGET", GetLocalInt(oCreature, "MCP_LEVEL_TARGET") > 0
        ? GetLocalInt(oCreature, "MCP_LEVEL_TARGET") : nTarget);
    DelayCommand(0.2, CL_Gear(oCreature));
}

// Call from the creature's OnSpawn wrapper after the original spawn script.
void CL_OnSpawn(object oCreature)
{
    if (GetLocalInt(oCreature, "MCP_LEVEL_DONE"))
    {
        if (GetLocalInt(oCreature, "MCP_CL_VERIFY")) DelayCommand(1.0, CL_Verify(oCreature));
        return;
    }
    if (GetLocalInt(oCreature, "MCP_LEVEL") <= 0 && GetLocalInt(oCreature, "MCP_LEVEL_REL") == 0
        && GetLocalInt(oCreature, "MCP_LEVEL_MIN") <= 0)
        return;
    int nTarget = CL_TargetLevel(oCreature);
    SetLocalInt(oCreature, "MCP_LEVEL_TARGET", nTarget);
    DelayCommand(0.3, CL_LevelStep(oCreature, nTarget));
}
`;
}

/** The one OnSpawn wrapper every forged creature uses: run its original spawn script, then level it. */
export function generateCreatureLevelWrapper(): string {
  return `// cf_spawn — OnSpawn wrapper for creatures built by forge_creature.
// Runs the creature's original spawn script (MCP_ORIG_SPAWN), then spawn-time levelling.
#include "${CREATURE_LEVEL_INCLUDE}"

void main()
{
    string sOriginal = GetLocalString(OBJECT_SELF, "MCP_ORIG_SPAWN");
    if (sOriginal != "") ExecuteScript(sOriginal, OBJECT_SELF);
    CL_OnSpawn(OBJECT_SELF);
}
`;
}
