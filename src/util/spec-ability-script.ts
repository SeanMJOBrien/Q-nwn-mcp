/**
 * Generator for the Special-Abilities random-caster runtime include
 * (`inc_spec_ability` by default).
 *
 * Companion system to bake_spec_ability_pool (spec-ability-pool.ts /
 * spec-ability-tools.ts), which bakes an OVERSIZED pool of eligible spells
 * onto a creature blueprint's SpecAbilityList at build time (every spell its
 * class/level could legally know, per classes.2da/cls_spgn_<class>.2da/
 * spells.2da — there is no runtime call that can add a new ability, so this
 * step cannot happen here). This include's SA_OnSpawn(oCreature), called
 * once per spawn, randomly marks a real-slot-sized SUBSET of that baked pool
 * "ready" via the engine's own SetSpellAbilityReady() and un-readies the
 * rest — so the same NPC can show up with a different effective loadout on
 * each playthrough, exactly like the existing inc_random_abil.nss system,
 * but via SpecAbilityList instead of MemorizedList.
 *
 * WHY A SECOND SYSTEM INSTEAD OF EXTENDING inc_random_abil.nss: that system
 * is split into two tiers because of a hard line in classes.2da
 * (MemorizesSpells) — Tier 1 (Cleric/Druid/Paladin/Ranger/Wizard) writes a
 * real memorized spellbook via SetMemorizedSpell(), but that call silently
 * respects GetMemorizedSpellCountByLevel()'s ceiling, which is 0 for any
 * level past the first on a never-live-leveled blueprint, and stays 0 for
 * Wizard specifically at level 2+ even after a real LevelUpHenchman() pass
 * (confirmed via three independent NWNX avenues, see that file's header).
 * Tier 2 (Bard/Sorcerer) has no runtime known-spell setter at all, so it
 * resorts to a local-JSON-array + ActionCastSpellAtObject(bCheat=TRUE) hack.
 *
 * SpecAbilityList sidesteps both problems: it is not gated by
 * MemorizesSpells, not subject to GetMemorizedSpellCountByLevel()'s ceiling,
 * and base-game monsters have used it for decades to fire innate spell-like
 * abilities via the stock combat AI with zero caster-class levels at all —
 * GetCreatureTalentBest()/GetCreatureTalentRandom() (which the default
 * nw_c2_default* AI scripts use to pick a combat action) select from
 * spells.2da-category-tagged talents the creature "has," which includes
 * SpecAbilityList entries. The cost is that eligibility has to be computed
 * ahead of time rather than entirely in NWScript at OnSpawn, since nothing
 * can ADD an ability at runtime — only toggle an existing one's ready state.
 *
 * Depends on nothing but base-game 2DAs and base-game EE engine functions
 * (GetSpellAbilityCount/GetSpellAbilitySpell/SetSpellAbilityReady, added
 * 1.88.8193.36) — no project-specific table, no NWNX. Portable to any other
 * vanilla EE module verbatim, PROVIDED the creature's SpecAbilityList pool
 * was already baked by bake_spec_ability_pool (or an equivalent hand-edit) —
 * this script does nothing useful on a creature with an empty pool.
 */

import { classPositionRollLoop } from "./nwscript-snippets.js";

export interface SpecAbilityScriptOptions {
  /** Include resref to write, so the usage comment names the real file. */
  includeName?: string;
}

/** Generate the full NWScript source for the Special-Abilities runtime include. */
export function generateSpecAbilityInclude(opts: SpecAbilityScriptOptions = {}): string {
  const includeName = opts.includeName ?? "inc_spec_ability";

  return `// Random caster special abilities — runtime "which pre-baked spells are
// active this playthrough" selection.
//
// GENERATED by nwn-mcp create_spec_ability_system — do not hand-edit. Rerun
// the tool to regenerate; hand edits are lost on regeneration.
//
// WHY: bake_spec_ability_pool bakes an OVERSIZED pool of every spell a
// caster's class/level could legally know onto its SpecAbilityList at build
// time (there is no runtime call that can add a new ability — only toggle an
// existing one's ready state). SA_OnSpawn, called once per spawn, picks a
// real-slot-sized random SUBSET of that pool and marks it ready via the
// engine's own SetSpellAbilityReady() — un-readying the rest — so the same
// NPC shows a different effective loadout each time the module loads. The
// creature's existing stock combat AI (nw_c2_default3, x0_ch_hen_combat, or
// whatever ScriptEndRound/ScriptEndCombatRound is already wired) picks these
// abilities up automatically via the standard talent system — no extra
// per-round hook needed, unlike inc_random_abil.nss's Tier 2 classes.
//
// Nothing here depends on this MCP server, a project-specific 2DA, or NWNX:
// only base-game classes.2da/cls_spgn_<class>.2da/spells.2da and base-game
// EE engine functions. Copy this file into any other vanilla EE module's
// script resources and it works unmodified, PROVIDED the creature's
// SpecAbilityList pool was already baked (bake_spec_ability_pool, or a
// hand-written equivalent following the same {Spell, SpellCasterLevel,
// SpellFlags} struct shape) — this script is a no-op on a creature whose
// SpecAbilityList is empty.
//
// WIRING — chain, never replace a creature's existing ScriptSpawn. Write a
// tiny per-role wrapper script and point create_creature_blueprint's
// \`scripts\` param at it:
//
//     #include "${includeName}"
//     void main()
//     {
//         ExecuteScript("nw_c2_default9", OBJECT_SELF); // or the henchman/original ScriptSpawn
//         SA_OnSpawn(OBJECT_SELF);
//     }
//
// No ScriptEndRound hook is needed — SpecAbilityList entries marked ready
// are used by the creature's normal combat AI like any other known spell.
//
// OPT-OUT: a caster NPC that needs a fixed, story-specific ability instead
// of a random one simply isn't wired this way — use
// create_creature_blueprint's \`spells\` param (SpecAbilityList) directly as
// before, and don't point ScriptSpawn at the wrapper above for that
// creature, and don't run bake_spec_ability_pool on it.
//
// KNOWN LIMITATION — multiclass creatures with two caster class positions
// that share a spell on both class lists: SA_RollClass runs once per class
// position and does not track which pool entries another position already
// claimed, so a shared spell's single physical SpecAbilityList entry can
// satisfy both positions' "is this ready" check at once without being
// double-counted against either budget (harmless — SetSpellAbilityReady is
// idempotent), but this slightly understates real variety for a dual-caster
// build. Single-class casters (the common case for generated NPCs) are
// unaffected.

// classes.2da's SpellcastingAbil column ("STR".."CHA") -> the matching
// ABILITY_* engine constant. Returns -1 for an unrecognized/empty value.
int SA_AbilityConstant(string sAbil)
{
    if (sAbil == "STR") return ABILITY_STRENGTH;
    if (sAbil == "DEX") return ABILITY_DEXTERITY;
    if (sAbil == "CON") return ABILITY_CONSTITUTION;
    if (sAbil == "INT") return ABILITY_INTELLIGENCE;
    if (sAbil == "WIS") return ABILITY_WISDOM;
    if (sAbil == "CHA") return ABILITY_CHARISMA;
    return -1;
}

// D&D 3.5 bonus spells per spell level from an ability modifier (PHB Table
// 1-1). Not encoded in any NWN 2DA — classes.2da/cls_spgn_<class>.2da give
// base slot counts only. 0 for nLevel outside 1-9 or nMod < nLevel.
int SA_BonusSpells(int nMod, int nLevel)
{
    if (nLevel < 1 || nLevel > 9) return 0;
    if (nMod < nLevel) return 0;
    return (nMod - nLevel) / 4 + 1;
}

// Roll one class position's active-ability subset. No-ops immediately for a
// non-caster class, an unused position (CLASS_TYPE_INVALID), a class below
// its MinCastingLevel, or a creature with an empty SpecAbilityList pool.
void SA_RollClass(object oCreature, int nClassType, int nClassLevel)
{
    if (nClassType == CLASS_TYPE_INVALID) return;
    if (Get2DAString("classes", "SpellCaster", nClassType) != "1") return;

    string sGainTable = GetStringLowerCase(Get2DAString("classes", "SpellGainTable", nClassType));
    if (GetStringLength(sGainTable) == 0) return;

    string sClassCol = Get2DAString("classes", "SpellTableColumn", nClassType);
    if (GetStringLength(sClassCol) == 0) return;

    string sMinLevel = Get2DAString("classes", "MinCastingLevel", nClassType);
    int nMinLevel = (GetStringLength(sMinLevel) > 0) ? StringToInt(sMinLevel) : 1;
    if (nClassLevel < nMinLevel) return;

    string sAbil = Get2DAString("classes", "SpellcastingAbil", nClassType);
    int nAbilConst = SA_AbilityConstant(sAbil);
    int nAbilMod = (nAbilConst >= 0) ? GetAbilityModifier(nAbilConst, oCreature) : 0;

    int nCount = GetSpellAbilityCount(oCreature);
    if (nCount == 0) return;

    // Bucket every SpecAbilityList index into its spell-level pool for THIS
    // class's own spells.2da column, in one flat pass. Ten independent flat
    // arrays selected by if/else-if, not a nested array-of-10 or a switch
    // assigning a json local per case — both were confirmed broken/unsafe in
    // this project's companion system (inc_random_abil.nss's header explains
    // why) and the same shape is reused here defensively, even though this
    // pool is per-creature and far smaller than that system's full spells.2da
    // scan.
    json jPool0 = JsonArray();
    json jPool1 = JsonArray();
    json jPool2 = JsonArray();
    json jPool3 = JsonArray();
    json jPool4 = JsonArray();
    json jPool5 = JsonArray();
    json jPool6 = JsonArray();
    json jPool7 = JsonArray();
    json jPool8 = JsonArray();
    json jPool9 = JsonArray();

    int i;
    for (i = 0; i < nCount; i++)
    {
        int nSpellId = GetSpellAbilitySpell(oCreature, i);
        string sCell = Get2DAString("spells", sClassCol, nSpellId);
        if (GetStringLength(sCell) == 0) continue;
        int nLvl = StringToInt(sCell);
        if (nLvl < 0 || nLvl > 9) continue;

        json jIdx = JsonInt(i);
        if (nLvl == 0) jPool0 = JsonArrayInsert(jPool0, jIdx);
        else if (nLvl == 1) jPool1 = JsonArrayInsert(jPool1, jIdx);
        else if (nLvl == 2) jPool2 = JsonArrayInsert(jPool2, jIdx);
        else if (nLvl == 3) jPool3 = JsonArrayInsert(jPool3, jIdx);
        else if (nLvl == 4) jPool4 = JsonArrayInsert(jPool4, jIdx);
        else if (nLvl == 5) jPool5 = JsonArrayInsert(jPool5, jIdx);
        else if (nLvl == 6) jPool6 = JsonArrayInsert(jPool6, jIdx);
        else if (nLvl == 7) jPool7 = JsonArrayInsert(jPool7, jIdx);
        else if (nLvl == 8) jPool8 = JsonArrayInsert(jPool8, jIdx);
        else if (nLvl == 9) jPool9 = JsonArrayInsert(jPool9, jIdx);
    }

    int nSpellLvl;
    for (nSpellLvl = 0; nSpellLvl <= 9; nSpellLvl++)
    {
        string sSlotStr = Get2DAString(sGainTable, "SpellLevel" + IntToString(nSpellLvl), nClassLevel - 1);
        int nBase = (GetStringLength(sSlotStr) > 0) ? StringToInt(sSlotStr) : 0;
        if (nBase <= 0) continue;

        int nBonus = (nSpellLvl == 0) ? 0 : SA_BonusSpells(nAbilMod, nSpellLvl);
        int nSlots = nBase + nBonus;

        json jPool = JsonArray();
        if (nSpellLvl == 0) jPool = jPool0;
        else if (nSpellLvl == 1) jPool = jPool1;
        else if (nSpellLvl == 2) jPool = jPool2;
        else if (nSpellLvl == 3) jPool = jPool3;
        else if (nSpellLvl == 4) jPool = jPool4;
        else if (nSpellLvl == 5) jPool = jPool5;
        else if (nSpellLvl == 6) jPool = jPool6;
        else if (nSpellLvl == 7) jPool = jPool7;
        else if (nSpellLvl == 8) jPool = jPool8;
        else jPool = jPool9;

        int nPoolSize = JsonGetLength(jPool);
        if (nPoolSize == 0) continue;

        jPool = JsonArrayTransform(jPool, JSON_ARRAY_SHUFFLE);
        int nPick = nSlots;
        if (nPick > nPoolSize) nPick = nPoolSize;

        int j;
        for (j = 0; j < nPick; j++)
            SetSpellAbilityReady(oCreature, JsonGetInt(JsonArrayGet(jPool, j)), TRUE);
    }
}

// Call once from a chained OnSpawn wrapper (see the header comment above).
// Resets every SpecAbilityList slot to not-ready, then rolls every class
// position oCreature has — safe to call on a non-caster or a creature with
// no baked pool, which no-ops. Idempotent: safe to call more than once on
// the same creature (e.g. a companion re-rolled after a deferred-leveling
// pass completes).
//
// GetClassByPosition/GetLevelByPosition's nClassPosition is 1-indexed (1, 2,
// or 3 — see nwscript.nss's own doc comment: "a single-class creature will
// only have a value in nClassLocation=1"). Loop 1..3, NOT 0..2 — 0 is always
// CLASS_TYPE_INVALID and silently wastes an iteration, and a 0..2 loop (the
// original, buggy version of this function) misses real position 3 entirely
// for a genuine triple-multiclass creature, even though it happens to still
// catch positions 1-2 since those fall inside 0..2's range too.
void SA_OnSpawn(object oCreature)
{
    if (!GetIsObjectValid(oCreature)) return;

    int nCount = GetSpellAbilityCount(oCreature);
    int i;
    for (i = 0; i < nCount; i++)
        SetSpellAbilityReady(oCreature, i, FALSE);

    ${classPositionRollLoop("p", "SA_RollClass")}
}
`;
}
