/**
 * Generator for the generic runtime-assertion include (`inc_spec_assert` by
 * default).
 *
 * `inc_spec_check.nss`'s `SPEC_VerifyCreature()` is hardwired to a fixed set
 * of creature-stat fields (race/appearance/class/level/package/feats/spells)
 * — exactly the "what should be built" gap CLAUDE.md's Verification Gate
 * section calls out: "generalizing the SPEC_* runtime-verification pattern
 * beyond companion stats to arbitrary custom quest/encounter scripts." This
 * include is that generalization: three bare assertion primitives
 * (`SPEC_AssertInt`/`SPEC_AssertString`/`SPEC_AssertBool`) any custom script —
 * a quest condition/action script, an encounter's spawn script, a trigger, a
 * dialog node — can call to get the exact same `[SPEC_OK]`/`[SPEC_FAIL]` log
 * line format `run_live_verification`'s parser
 * (`src/util/verify-server/result.ts`) already recognizes. No parser changes
 * needed — that parser was written generically from the start.
 *
 * Unlike `SPEC_VerifyCreature()` (one `[SPEC_OK]` line only after every field
 * on a creature passes), each assertion here logs immediately and
 * independently — one line per call. See docs/runtime-verification-spec.md
 * §4/§5 for the full design and the standing status markers.
 */

export interface SpecAssertOptions {
  /** Include resref to write, so the usage comment names the real file. */
  includeName?: string;
}

/** Generate the full NWScript source for the generic spec-assertion include. */
export function generateSpecAssertInclude(opts: SpecAssertOptions = {}): string {
  const includeName = opts.includeName ?? "inc_spec_assert";

  return `// Generic runtime assertion primitives for custom quest/encounter scripts.
//
// GENERATED by nwn-mcp create_spec_assertions — do not hand-edit. Rerun the
// tool to regenerate.
//
// inc_spec_check.nss's SPEC_VerifyCreature() only checks a fixed set of
// creature-stat fields. This generalizes the same [SPEC_OK]/[SPEC_FAIL] log
// protocol to ANY runtime condition — not just creature stats — so a custom
// quest condition/action script, an encounter's spawn script, a trigger, or
// a dialog node can report pass/fail the same way, and run_live_verification
// picks it up with zero additional parsing. See
// docs/runtime-verification-spec.md §4/§5.
//
// Gated by MCP_VERIFY_MODE, the same module-local switch inc_spec_check.nss
// uses (module.ifo has no VarTable to bake a static flag into) — a no-op in
// any module not built for nwn-mcp's own verification.
//
// Each call logs IMMEDIATELY and INDEPENDENTLY — one [SPEC_OK]/[SPEC_FAIL]
// line per call, unlike SPEC_VerifyCreature's "one line after every field
// passes" bundling. A caller that wants bundled all-or-nothing behavior
// across several asserts should track its own pass flag and log a final
// combined result itself, the same way SPEC_VerifyCreature does — these are
// deliberately the bare primitive, not a bundling mechanism.
//
// sField/sExpected/sActual must not contain spaces — the log parser's regex
// (SPEC_FAIL_RE in src/util/verify-server/result.ts) splits on whitespace.
// Use a short slug for sField ("fired", "count", "hostile") and a
// space-free stringified value for sExpected/sActual.
//
// Log protocol (identical to inc_spec_check's — grep the server log for
// these after a headless run):
//   [SPEC_OK] tag=<sTag> field=<sField>
//   [SPEC_FAIL] tag=<sTag> field=<sField> expected=<x> actual=<y>
//
// Usage from any custom script — a quest condition script, an encounter's
// spawn script, a trigger, a dialog node action script, anything:
//
//     #include "${includeName}"
//     void main()
//     {
//         int nSpawned = GetLocalInt(OBJECT_SELF, "ENC_SPAWNED_COUNT");
//         SPEC_AssertInt("my_encounter", "spawn_count", 5, nSpawned);
//     }

// Integer equality assertion.
void SPEC_AssertInt(string sTag, string sField, int nExpected, int nActual)
{
    if (!GetLocalInt(GetModule(), "MCP_VERIFY_MODE")) return;

    if (nExpected == nActual)
        WriteTimestampedLogEntry("[SPEC_OK] tag=" + sTag + " field=" + sField);
    else
        WriteTimestampedLogEntry("[SPEC_FAIL] tag=" + sTag + " field=" + sField +
            " expected=" + IntToString(nExpected) + " actual=" + IntToString(nActual));
}

// String equality assertion. Pass space-free values (e.g. a tag, a resref, a
// slug) — see the space restriction noted above.
void SPEC_AssertString(string sTag, string sField, string sExpected, string sActual)
{
    if (!GetLocalInt(GetModule(), "MCP_VERIFY_MODE")) return;

    if (sExpected == sActual)
        WriteTimestampedLogEntry("[SPEC_OK] tag=" + sTag + " field=" + sField);
    else
        WriteTimestampedLogEntry("[SPEC_FAIL] tag=" + sTag + " field=" + sField +
            " expected=" + sExpected + " actual=" + sActual);
}

// Boolean condition assertion (e.g. GetIsEnemy(oA, oB), GetIsObjectValid(o)).
// Always expects TRUE. sActualDescription lets the caller name what a FALSE
// result means in context (e.g. "not_enemies") instead of a bare "FALSE" —
// pass "" (the default) to just log TRUE/FALSE.
void SPEC_AssertBool(string sTag, string sField, int bCondition, string sActualDescription = "")
{
    if (!GetLocalInt(GetModule(), "MCP_VERIFY_MODE")) return;

    if (bCondition)
    {
        WriteTimestampedLogEntry("[SPEC_OK] tag=" + sTag + " field=" + sField);
        return;
    }

    string sActual = (sActualDescription != "") ? sActualDescription : "FALSE";
    WriteTimestampedLogEntry("[SPEC_FAIL] tag=" + sTag + " field=" + sField +
        " expected=TRUE actual=" + sActual);
}
`;
}
